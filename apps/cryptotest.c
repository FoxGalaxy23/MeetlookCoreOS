static bool_t g_all_ok = TRUE;

static void print_hex(const u8 *d, u32 n) {
    static const char hex[] = "0123456789abcdef";
    char line[65];
    u32 i;
    for (i = 0; i < n && i < 32; i++) {
        line[i * 2] = hex[d[i] >> 4];
        line[i * 2 + 1] = hex[d[i] & 0xF];
    }
    line[i * 2] = '\0';
    printf("%s", line);
}

static void check_sha256(const char *label, const char *msg, u32 len, const u8 *expected) {
    u8 out[SHA256_DIGEST_SIZE];
    sha256((const u8 *)msg, len, out);

    bool_t ok = TRUE;
    for (u32 i = 0; i < SHA256_DIGEST_SIZE; i++) {
        if (out[i] != expected[i]) { ok = FALSE; break; }
    }

    printf("sha256(%s): ", label);
    print_hex(out, SHA256_DIGEST_SIZE);
    printf(" -- %s\n", ok ? "OK" : "FAIL");
    if (!ok) g_all_ok = FALSE;
}

