#ifndef TCP_H
#define TCP_H

#include "types.h"
#include "net.h"

/* tcp.h -- минимальный клиентский TCP (RFC 793): только активное открытие
 * соединения (нет LISTEN/accept -- серверная часть этой ОС не нужна,
 * задание -- "ping, wget, curl", это всё клиенты). Существенные
 * упрощения относительно полного стека:
 *
 *   - "Stop-and-wait" передача: на каждый вызов tcp_send() в сети
 *     одновременно находится не больше одного неподтверждённого
 *     сегмента данных (следующий кусок отправляется только после ACK на
 *     предыдущий, с повторной отправкой по таймауту). Полноценное
 *     скользящее окно с несколькими сегментами в полёте не реализовано --
 *     для HTTP-запросов (обычно один сегмент) и типичных ответов через
 *     локальную сеть/QEMU это не критично для практической пригодности.
 *   - Входящие данные принимаются только "по порядку" (in-order):
 *     сегмент с seq, не равным ожидаемому rcv_nxt, отбрасывается без
 *     подтверждения -- это совершенно штатно по RFC 793 (просто нет
 *     буфера пересборки) и заставляет отправителя переслать сегмент
 *     повторно, как и предусмотрено протоколом.
 *   - Постоянная опция MSS в SYN, без window scaling, SACK, timestamps.
 *
 * Соединение представлено небольшим целым (handle) -- индексом в
 * фиксированном пуле (см. TCP_MAX_SOCKETS в tcp.c), в духе остальных
 * хендл-таблиц этой ОС (см. include/ipc.h). */

#define TCP_MAX_SOCKETS 8u

void tcp_init(void);

/* Вызывается ip_input() для IP_PROTO_TCP. */
void tcp_input(ip_addr_t src, const u8 *payload, u32 len);

/* Активное открытие: SYN -> ждём SYN+ACK -> ACK. Блокирует не дольше
   timeout_ms. Возвращает handle (>=0) либо <0 при неудаче (нет ответа,
   RST от удалённой стороны, нет свободных сокетов). */
s32 tcp_connect(ip_addr_t dst_ip, u16 dst_port, u32 timeout_ms);

/* Отправляет len байт (см. общий комментарий про stop-and-wait), блокируя
   до тех пор, пока все они не будут подтверждены, либо до истечения
   timeout_ms суммарно. Возвращает число реально отправленных и
   подтверждённых байт (может быть меньше len при таймауте/разрыве). */
s32 tcp_send(s32 h, const void *buf, u32 len, u32 timeout_ms);

/* Возвращает уже накопленные в приёмном буфере сокета данные (без
   ожидания, если что-то уже есть; иначе ждёт до timeout_ms). 0 означает
   "удалённая сторона закрыла соединение (FIN) и больше данных не будет"
   (аналог EOF); <0 -- таймаут (данных не было и не появилось) либо
   ошибка (неверный handle, соединение разорвано по RST). */
s32 tcp_recv(s32 h, void *buf, u32 maxlen, u32 timeout_ms);

/* Закрывает соединение (посылает FIN, если оно ещё не было получено от
   удалённой стороны -- иначе просто ACK на её FIN) и освобождает handle.
   Не блокирует долго (короткая попытка корректного закрытия с небольшим
   таймаутом, после которого сокет всё равно освобождается -- полноценный
   TIME_WAIT не реализован, это не сервер, повторное использование
   локального порта конфликтами не грозит: они выбираются по кругу из
   большого диапазона, см. tcp.c). */
void tcp_close(s32 h);

#endif
