#ifndef TIMER_H
#define TIMER_H

#include "types.h"

/* timer.h -- системный таймер на базе PIT (Intel 8253/8254), канал 0,
 * приходит как IRQ0. Это "пульс" всей многозадачности: именно по этому
 * прерыванию scheduler.c принимает решение, не пора ли снять текущую
 * задачу с процессора и дать поработать следующей (см. task.h).
 */

/* Программирует PIT на генерацию IRQ0 с частотой freq_hz раз в секунду
   (канал 0, режим 3 -- square wave) и размаскирует IRQ0 на PIC.
   Разумный диапазон -- от ~18 (минимум, на который способен сам PIT
   при 16-битном делителе) до нескольких тысяч Гц; для планировщика
   обычно достаточно 100-1000 Гц. */
void timer_init(u32 freq_hz);

/* Количество тиков таймера с момента timer_init(). Переполняется через
   ~2^64 тиков, т.е. на практике никогда. */
u64 timer_ticks(void);

/* Частота, с которой был запрограммирован PIT в последнем timer_init()
   (в Гц). Нужна task_sleep() (см. task.h/task.c), чтобы перевести
   миллисекунды в целое число тиков, не завязываясь на конкретное
   значение (сейчас 100 Гц, см. kernel.c) магической константой.
   Возвращает 0, если timer_init() ещё не вызывался. */
u32 timer_frequency(void);

#endif
