#ifndef PMM_H
#define PMM_H

#include "types.h"
#include "bootinfo.h"

/* pmm.h -- менеджер физической памяти (Physical Memory Manager).
 *
 * MeetlookCoreOS отображает первые 4 GiB физической памяти "один в
 * один" на виртуальные адреса ещё на этапе загрузки (boot/boot.s), так
 * что виртуальный и физический адрес всегда совпадают. Поэтому PMM
 * не занимается отображением страниц -- только учётом того, какие
 * страницы (кадры, "frames") по 4 KiB уже кому-то принадлежат, а какие
 * свободны. Это классический битовый аллокатор (bitmap allocator):
 * один бит на кадр, 0 -- свободен, 1 -- занят.
 *
 * Это фундамент для всего остального: без него ни куча ядра (kheap.c),
 * ни будущий менеджер процессов не могут честно ответить на вопрос
 * "эта память ещё чья-то или уже ничья?".
 */

#define PMM_FRAME_SIZE 4096u

/* Инициализация: разбирает карту физической памяти из bi (см.
   include/bootinfo.h, NOGRUB_PLAN.md Фаза A -- bi заполняет
   переходник конкретного загрузчика, например
   kernel/bootinfo_multiboot.c для GRUB, а не эта функция напрямую),
   строит битовую карту, резервирует регион BIOS/reset-vector (первый
   1 MiB), образ самого ядра и буфер загрузчика пользовательских
   бинарников (APP_LOAD_ADDR..+APP_MAX_SIZE, см. include/loader.h) --
   эти области никогда не будут выданы аллокатором. Если
   bootinfo_usable_ram_extent(bi) вернёт 0 (загрузчик не предоставил
   информацию о памяти), применяется консервативный запасной вариант
   (32 MiB) -- то же поведение, что и раньше при отсутствии
   multiboot-флага MULTIBOOT_INFO_MEMORY. */
void pmm_init(const boot_info_t *bi);

/* Резервирует произвольный регион [addr, addr+len) -- помечает все
   покрываемые им кадры как занятые, не выдавая их аллокатору. Нужно,
   например, kheap.c, чтобы застолбить место под кучу ядра. Обрезает
   len по границе доступной памяти, если регион выходит за её пределы. */
void pmm_reserve_region(void *addr, u32 len);

/* Выделяет один свободный физический кадр (4 KiB), выровненный по
   границе страницы. Возвращает 0, если свободных кадров не осталось. */
void *pmm_alloc_frame(void);

/* Выделяет `count` подряд идущих свободных кадров одним куском.
   Возвращает 0, если такого подряд идущего свободного участка нет. */
void *pmm_alloc_frames(u32 count);

/* Освобождает ранее выделенный кадр/кадры. addr должен быть адресом,
   ранее возвращённым pmm_alloc_frame()/pmm_alloc_frames() (или любым
   адресом внутри уже занятого кадра -- освобождение всегда идёт по
   границе кадра, в который попадает addr). Двойное освобождение
   безопасно (игнорируется), т.к. используется учёт "уже свободен". */
void pmm_free_frame(void *addr);
void pmm_free_frames(void *addr, u32 count);

/* ---- учёт ссылок на кадр -- нужен для copy-on-write (kernel/paging.c) ----
 *
 * Обычный pmm_free_frame() ничего не знает про то, что один и тот же
 * физический кадр может быть отображён сразу в двух адресных
 * пространствах (родитель и потомок после fork(), пока никто из них не
 * записал в разделяемую страницу). pmm_alloc_frame(s)() неявно
 * инициализирует счётчик только что выданного кадра в 1; каждый
 * дополнительный "совладелец" обязан сам вызвать pmm_frame_addref()
 * (см. as_clone_cow() в kernel/paging.c), а при потере своей ссылки --
 * pmm_frame_release(), который в отличие от pmm_free_frame() реально
 * освобождает кадр аллокатору только тогда, когда счётчик доходит до 0. */
void pmm_frame_addref(void *addr);
void pmm_frame_release(void *addr);


/* ---- статистика, в т.ч. для команды shell'а meminfo и для kapi ---- */
u32 pmm_total_frames(void);
u32 pmm_free_frame_count(void);
u32 pmm_used_frame_count(void);
u32 pmm_total_memory_bytes(void);
u32 pmm_free_memory_bytes(void);

#endif
