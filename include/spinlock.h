#ifndef SPINLOCK_H
#define SPINLOCK_H

#include "types.h"

/* spinlock.h -- настоящий атомарный спинлок для SMP (см. include/sync.h
 * за старой, однопроцессорной моделью и общий комментарий в include/smp.h
 * за тем, почему её пришлось потеснить).
 *
 * До этого файла ЕДИНСТВЕННЫМ примитивом взаимного исключения в ядре
 * было отключение прерываний (cli/sti, см. save_and_disable_interrupts()
 * в kernel/task.c, irq_save()/irq_restore() в kernel/sync.c и kernel/ipc.c).
 * На одном ядре этого достаточно: пока прерывания выключены, вообще
 * ничего другого на CPU не выполняется, значит никто не может помешать
 * ровно посреди критической секции. С появлением второго (и далее) ядра
 * (см. include/smp.h) это предположение рушится: cli на CPU0 запрещает
 * прерывания ТОЛЬКО на CPU0 -- CPU1 в это время может преспокойно
 * выполнять тот же самый код и читать/писать те же самые данные. Нужен
 * настоящий примитив, который синхронизирует именно МЕЖДУ ядрами, а не
 * только внутри одного потока прерываний.
 *
 * spinlock_t -- простейший TAS-спинлок (test-and-set) на одном общем
 * слове, захватываемый атомарной инструкцией CPU (lock xchg на x86_64,
 * это ровно то, что делает __atomic_exchange_n с memory order
 * __ATOMIC_ACQUIRE) -- никакого учёта владельца, никакой очереди
 * ожидающих: CPU, которому не досталось, просто крутится в цикле
 * (busy-wait), проверяя лок снова и снова, пока не освободится. Это
 * осознанный выбор для этой ОС: критические секции, которые он
 * защищает (общий список задач планировщика, битовая карта PMM, куча
 * ядра, см. kernel/task.c/pmm.c/kheap.c), выполняются считанные
 * инструкции -- строить под них что-то сложнее (MCS-очереди, тикетные
 * локи с честным FIFO-порядком) было бы избыточно для системы с
 * небольшим числом ядер.
 *
 * ВАЖНО (то же предупреждение, что в include/sync.h про мьютексы):
 * спинлок -- это БУСИ-WAIT, а не сон. Значит НЕЛЬЗЯ удерживать спинлок
 * и одновременно звать что-то, что блокируется (mutex_lock(),
 * sem_wait(), task_block_self()...) -- на однопроцессорной системе это
 * означало бы: другая задача, которая должна была бы освободить лок,
 * никогда не получит процессор (мы же его не отдаём, крутясь в
 * busy-wait). На SMP то же самое, только ещё и с несколькими ядрами,
 * бесполезно жгущими такты в ожидании друг друга. Спинлоки в этом ядре
 * предназначены ТОЛЬКО для очень коротких критических секций внутри
 * kernel/task.c, kernel/pmm.c, kernel/kheap.c, kernel/sync.c,
 * kernel/apic.c/smp.c -- не для пользовательского/прикладного кода
 * (там по-прежнему mutex_t/semaphore_t/condvar_t из include/sync.h). */

typedef struct spinlock {
    volatile u32 locked; /* 0 -- свободен, 1 -- занят; трогать только через spin_lock()/spin_unlock() ниже */
} spinlock_t;

#define SPINLOCK_INIT { 0 }

void spinlock_init(spinlock_t *lock);

/* Захватывает лок, крутясь в busy-wait, пока он занят. НЕ трогает флаг
   прерываний -- если код может быть прерван таймером/IRQ на ЭТОМ ЖЕ
   CPU во время удержания лока (а таймер, в свою очередь, может внутри
   себя захотеть тот же самый лок -- см. scheduler_tick()), это привело
   бы к самозаклиниванию (одноядерный deadlock, не путать с
   межъядерным). Для кода, который может быть вызван с разрешёнными
   прерываниями, используйте spin_lock_irqsave()/spin_unlock_irqrestore()
   ниже, а не эту пару напрямую. */
void spin_lock(spinlock_t *lock);

/* Пытается захватить без ожидания. TRUE -- получилось, лок за вами. */
bool_t spin_trylock(spinlock_t *lock);

void spin_unlock(spinlock_t *lock);

/* ---- IRQ-safe варианты -- то, что реально используется по всему ядру ----
 *
 * Комбинация "выключить прерывания НА ЭТОМ CPU" (защита от самого себя,
 * т.е. от таймерного тика/IRQ, прерывающего нас же посреди критической
 * секции) + "захватить спинлок" (защита от ВСЕХ ОСТАЛЬНЫХ CPU,
 * одновременно решивших залезть в те же данные) -- это ровно то, что
 * нужно любому обработчику критической секции в SMP-ядре, разделяемой
 * между обычным кодом задач и обработчиками прерываний. Возвращает
 * ИСХОДНЫЙ флаг IF (как save_and_disable_interrupts() в task.c) --
 * восстанавливать нужно обязательно его, а не жёстко sti, ровно по тем
 * же причинам вложенности, что описаны в комментариях kernel/task.c и
 * kernel/sync.c. */
u64 spin_lock_irqsave(spinlock_t *lock);
void spin_unlock_irqrestore(spinlock_t *lock, u64 flags);

#endif
