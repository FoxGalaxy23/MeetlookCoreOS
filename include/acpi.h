#ifndef ACPI_H
#define ACPI_H

#include "types.h"

/* acpi.h -- минимальный разбор ACPI-таблиц, ровно настолько, насколько
 * нужно SMP-загрузке (kernel/smp.c): узнать, сколько в системе логических
 * ядер и каков физический APIC ID (см. include/apic.h) у каждого из них.
 * Ни ACPI-выключение питания, ни AML/DSDT, ни что-либо ещё из
 * необъятного ACPI здесь не разбирается -- только RSDP -> RSDT/XSDT ->
 * MADT -> список "Processor Local APIC" записей.
 *
 * Почему это вообще нужно: PC не сообщает "сколько у меня ядер и как их
 * зовут" никаким портом ввода-вывода или простым CPUID-запросом,
 * одинаковым на всех платформах (CPUID даёт топологию текущего ядра, но
 * не список ВСЕХ остальных) -- эта информация приходит из прошивки
 * (BIOS/UEFI) через таблицы ACPI, которые прошивка строит при старте
 * машины и оставляет в обычной ОЗУ для операционной системы. */

#define ACPI_MAX_CPUS 32u /* тот же практический потолок, что и SMP_MAX_CPUS в percpu.h */

typedef struct acpi_cpu_info {
    u32 apic_id;
    bool_t enabled; /* FALSE -- слот описан прошивкой, но ядро физически не годно к использованию
                        (Intel SDM/ACPI спецификация допускает такие записи, например про
                        ядра, отключённые из-за брака при производстве) */
} acpi_cpu_info_t;

/* Ищет RSDP (BIOS EBDA + диапазон 0xE0000-0xFFFFF, см. ACPI Spec §5.2.5.1),
   затем RSDT/XSDT -> MADT, и заполняет out_cpus (до max_cpus штук).
   Возвращает число найденных записей "Processor Local APIC" (обычно
   равно числу логических ядер, доступных прошивке), либо 0, если ACPI
   недоступен вовсе (старые/нестандартные машины, некоторые урезанные
   конфигурации QEMU) -- в этом случае smp_init() (kernel/smp.c) честно
   деградирует до единственного ядра (BSP), не пытаясь ничего поднимать. */
u32 acpi_find_cpus(acpi_cpu_info_t *out_cpus, u32 max_cpus);

#endif
