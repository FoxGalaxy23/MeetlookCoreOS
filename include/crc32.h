#ifndef CRC32_H
#define CRC32_H

#include "types.h"

/* crc32.h -- CRC-32/ISO-HDLC (полином 0xEDB88320, тот же алгоритм, что
 * в zlib, PKZIP, Ethernet, PNG) -- ЕДИНСТВЕННАЯ причина, по которой этот
 * файл вообще появился: GPT (UEFI_PLAN.md, Фаза A) обязан включать
 * CRC32 заголовка и массива записей разделов -- настоящие прошивки эту
 * контрольную сумму реально проверяют, ошибка = "диск считается
 * неразмеченным". mbr.c такого не требовал вовсе.
 *
 * Значение при пустом входе (len=0) -- 0, что позволяет вызывающему
 * коду накапливать CRC по кускам: crc32(crc32(0, buf1, len1), buf2, len2)
 * даёт тот же результат, что crc32(0, buf1+buf2 целиком, len1+len2) --
 * стандартное свойство этого алгоритма, тем же способом, каким это
 * делает zlib. */

/* Возвращает CRC32 данных buf[0..len). initial -- значение "накопителя"
 * с предыдущего вызова (0, если считаем с нуля -- см. общий комментарий
 * выше про накопление по кускам). */
u32 crc32(u32 initial, const void *buf, u32 len);

#endif
