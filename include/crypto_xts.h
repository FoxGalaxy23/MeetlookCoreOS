#ifndef CRYPTO_XTS_H
#define CRYPTO_XTS_H

#include "types.h"
#include "crypto_aes.h"

/* crypto_xts.h -- AES-XTS-256 (IEEE P1619 / NIST SP 800-38E), режим для
 * посекторного шифрования диска. См. ATOMIC_PLAN.md, Фаза 1 (последний
 * недостающий примитив) и Фаза 4 (crypto block layer, реальный
 * потребитель) -- ЭТИМ файлом шифруется/расшифровывается тело
 * пользовательского образа (include/userimg.h) сектор за сектором.
 *
 * Почему не CBC/ECB для этого -- см. общий комментарий у Фазы 1
 * ATOMIC_PLAN.md: диск читают/пишут секторами В ЛЮБОМ порядке, без
 * доступа к предыдущим/последующим секторам (в отличие от файла,
 * читаемого последовательно) -- CBC требует IV, зависящий от
 * предыдущего блока ЭТОГО ЖЕ потока шифрования, ECB вообще не
 * скрывает повторяющиеся 16-байтные блоки (типичные для sparse-файлов,
 * нулевых страниц и т.п.). XTS решает это тем, что каждый "data unit"
 * (здесь -- ровно один сектор) шифруется НЕЗАВИСИМО, с тюком (tweak),
 * порождённым из номера сектора, без цепочки между секторами.
 *
 * КЛЮЧЕВОЙ МАТЕРИАЛ -- XTS-AES-256 по спецификации требует ДВА
 * независимых 256-битных AES-ключа (Key1 -- шифрует данные, Key2 --
 * шифрует тюк), то есть 64 байта, а не 32. userimg.h хранит и
 * оборачивает только ОДИН 32-байтный master_key (см. её общий
 * комментарий) -- этого достаточно, оба XTS-подключа выводятся отсюда
 * же через aes_xts_key_derive_from_master() (HMAC-SHA256 с разными
 * метками, тот же принцип, что HKDF-Expand с разным "info": один
 * источник энтропии, два независимых по построению подключа для двух
 * разных целей). Так формат заголовка не меняется, а этот файл сам
 * решает, сколько ключевого материала ему на самом деле нужно.
 *
 * "data unit" здесь ВСЕГДА ровно один сектор (512 байт = 32 блока
 * AES ровно, без остатка) -- поэтому ciphertext stealing (нужен в
 * общем XTS для данных, чья длина не кратна 16 байтам) здесь НЕ
 * реализован: он просто никогда не понадобится при работе с целыми
 * секторами по 512 байт, и не стоит тащить лишний, никогда не
 * исполняемый код ради формальной полноты спецификации.
 *
 * Как и остальные crypto_*.h -- никакого I/O здесь нет, чистая логика
 * над буферами в памяти; кто и когда читает/пишет сектор с диска
 * (через sys_disk_read_raw()/write_raw()) -- решает вызывающий код
 * (Фаза 4), не этот файл. */

#define XTS_MASTER_KEY_LEN 32u  /* см. USERIMG_MASTER_KEY_LEN, include/userimg.h -- то же значение */
#define XTS_SECTOR_SIZE    512u /* = 32 * AES_BLOCK_SIZE ровно, см. общий комментарий выше про ciphertext stealing */

typedef struct {
    aes256_key_t key1; /* шифрует сами данные */
    aes256_key_t key2; /* шифрует тюк (номер сектора) */
} aes_xts_key_t;

/* Выводит оба XTS-подключа из master_key (см. общий комментарий выше).
 * Разворачивает key schedule ОБОИХ ключей внутри xk -- дальше
 * aes_xts_encrypt_sector()/decrypt_sector() можно звать много раз без
 * повторного разворачивания. */
void aes_xts_key_derive_from_master(const u8 master_key[XTS_MASTER_KEY_LEN], aes_xts_key_t *xk);

/* Шифрует/расшифровывает РОВНО ОДИН сектор (XTS_SECTOR_SIZE=512 байт).
 * sector_number -- номер "data unit" (у нас -- абсолютный или
 * относительный LBA, тюк строится из него как 128-битное
 * little-endian число, см. IEEE P1619 §5.1) -- ОБЯЗАН быть одним и
 * тем же для одного и того же сектора при шифровании и при
 * расшифровке, иначе получится мусор (это не ошибка формата -- в этом
 * и есть смысл tweak-а: один и тот же plaintext на разных LBA даёт
 * разный ciphertext). in и out могут совпадать (шифрование на месте). */
void aes_xts_encrypt_sector(const aes_xts_key_t *xk, u64 sector_number,
                             const u8 in[XTS_SECTOR_SIZE], u8 out[XTS_SECTOR_SIZE]);
void aes_xts_decrypt_sector(const aes_xts_key_t *xk, u64 sector_number,
                             const u8 in[XTS_SECTOR_SIZE], u8 out[XTS_SECTOR_SIZE]);

#endif
