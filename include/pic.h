#ifndef PIC_H
#define PIC_H

#include "types.h"

/* pic.h -- программируемый контроллер прерываний 8259 (Programmable
 * Interrupt Controller), ведущий (master, IRQ0-7) и ведомый (slave,
 * IRQ8-15).
 *
 * По умолчанию, после сброса машины, PIC отправляет IRQ0-7 на векторы
 * 0x08-0x0F и IRQ8-15 на 0x70-0x77 -- это напрямую пересекается с
 * зарезервированными Intel исключениями CPU (0x00-0x1F, см. isr.h).
 * Например, таймер (IRQ0) без ремапа прилетел бы на вектор 0x08, который
 * уже занят исключением Double Fault -- ядро не смогло бы отличить одно
 * от другого. pic_remap() сдвигает векторы IRQ на 32-47, где они уже
 * не конфликтуют ни с чем.
 */

#define PIC1_COMMAND 0x20   /* ведущий PIC: порт команд */
#define PIC1_DATA    0x21   /* ведущий PIC: порт данных / маски */
#define PIC2_COMMAND 0xA0   /* ведомый PIC: порт команд */
#define PIC2_DATA    0xA1   /* ведомый PIC: порт данных / маски */

#define PIC_EOI      0x20   /* команда "End Of Interrupt" */

#define PIC1_VECTOR_OFFSET 32   /* IRQ0..7  -> векторы 32..39 */
#define PIC2_VECTOR_OFFSET 40   /* IRQ8..15 -> векторы 40..47 */

/* Переинициализирует оба PIC (ICW1-ICW4) и сдвигает их векторы на
   offset1/offset2. Все IRQ остаются замаскированными после вызова --
   конкретные драйверы (timer.c, keyboard.c, ...) должны явно
   размаскировать нужный им IRQ через pic_clear_mask(). */
void pic_remap(u8 offset1, u8 offset2);

/* Сообщает PIC (и ведомому, если irq >= 8, и в любом случае ведущему),
   что обработка прерывания завершена, и он может присылать следующее.
   Без этого конкретный IRQ (а на ведущем PIC -- вообще все IRQ >= него)
   перестанет приходить после первого же раза. */
void pic_send_eoi(u8 irq);

/* Маскирует (запрещает) / размаскирует (разрешает) конкретный IRQ (0-15)
   на уровне контроллера, независимо от IF в EFLAGS и от IDT. */
void pic_set_mask(u8 irq);
void pic_clear_mask(u8 irq);

#endif
