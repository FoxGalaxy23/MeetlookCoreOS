#ifndef UACCESS_H
#define UACCESS_H

#include "types.h"

/* uaccess.h -- проверка указателей, приходящих из ring 3 через аргументы
 * системных вызовов (см. include/sysabi.h, kernel/syscall.c).
 *
 * Раньше (общее адресное пространство на всю систему) это была проверка
 * "лежит ли диапазон в единственном активном сейчас регионе". Теперь у
 * каждого процесса собственное адресное пространство (см.
 * include/paging.h), поэтому проверка делается относительно ТЕКУЩЕЙ
 * задачи (task_current()->as, include/task.h) -- см. as_range_is_user_accessible()
 * в kernel/paging.c: диапазон обязан целиком лежать внутри одного из
 * отведённых ЭТОМУ процессу регионов (код/стек/куча), по их максимально
 * допустимой величине.
 *
 * Как и раньше: ring0-код (сам обработчик syscall) технически и так
 * может прочитать/записать что угодно в любом месте identity-map --
 * проверка не про физическую невозможность доступа, а про то, чтобы
 * ядро не доверяло указателю, который программа передала через регистр,
 * и не позволяло ей чужими руками (руками ядра) прочитать/записать
 * чужую или ядерную память. */

/* TRUE, если весь диапазон [ptr, ptr+len) целиком лежит внутри одного из
   регионов, отведённых ТЕКУЩЕЙ (task_current()) процессной задаче. Если
   текущая задача не является процессом (task_current()->as == 0, т.е.
   это поток ядра -- такое возможно только в god-режиме, у которого
   вообще нет собственной проверки памяти, см. kernel/loader.c), всегда
   возвращает FALSE, кроме len == 0 (нулевая длина -- это "ничего не
   читать/писать", безопасно всегда). */
bool_t uaccess_check(const void *ptr, u32 len);

#endif
