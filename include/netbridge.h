#ifndef NETBRIDGE_H
#define NETBRIDGE_H

#include "types.h"

/* netbridge.h -- Фаза 4, подшаг 3 (см. CONTAINER_ARCHITECTURE.md): канал
 * кадров между ядром (где остаётся весь сетевой СТЕК -- содержимое net/) и
 * драйвером сетевой карты, вынесенным в user-space контейнер (Фаза 4,
 * подшаг 4 -- см. apps/rtl8139d.c и kernel/netdrv.c).
 * Строится на CAP_IO/CAP_IRQ из подшагов 4.1/4.2: у драйвера-контейнера
 * уже есть всё нужное, чтобы САМОМУ говорить с железом карты (регистры
 * через порты, пробуждение по IRQ) -- не хватало только способа
 * получить от ядра "вот кадр, который нужно отправить" и отдать ядру
 * "вот кадр, который только что пришёл", не деля с ним ни адресное
 * пространство, ни прямой вызов функции.
 *
 * ---- Почему не existing mqueue_t (include/ipc.h) ----
 *
 * У очередей сообщений общего назначения MQ_MAX_MSG_SIZE == 256 байт --
 * с большим запасом хватает для демо-IPC (apps/ipctest.c), но НЕ хватает
 * для целого Ethernet-кадра (до NETBRIDGE_MAX_FRAME == 1514 байт).
 * Поднять MQ_MAX_MSG_SIZE для ВСЕХ очередей в системе только ради этого
 * одного канала means раздуть память под MQ_MAX_QUEUES x MQ_MAX_MSGS
 * слотов почти в 6 раз -- отдельная маленькая очередь, заточенная под
 * ровно этот размер (и всего под 2 экземпляра -- TX и RX, не
 * MQ_MAX_QUEUES), обходится дешевле и не трогает никакой другой код,
 * уже использующий mqueue_t. Тот же принцип, что уже применён к
 * irqbridge.c -- отдельный маленький мост поверх примитивов sync.h,
 * а не переиспользование чужой структуры не по размеру.
 *
 * ---- Модель конкурентности (см. общий комментарий в include/net.h) ----
 *
 * TX (ядро -> драйвер-контейнер, "вот кадр, отправь его"): производитель
 * -- net-стек. До Фазы 4.4 он мог звать нас (тогда ещё rtl8139_send())
 * ИЗ НАСТОЯЩЕГО контекста прерывания (ARP/ICMP-ответ, собранный прямо
 * внутри обработчика приёма rtl8139_irq_handler()) -- после 4.4 такого
 * контекста для ЭТОЙ карты в ядре больше не существует (приём теперь
 * разбирается в обычном потоке netbridge_rx_pump(), см. общий комментарий
 * в include/net.h), но netbridge_push_tx_frame() всё равно НЕ блокирует и
 * не использует mutex_t/condvar_t (см. предупреждение в include/sync.h --
 * их нельзя звать из обработчика прерывания): преемптивный планировщик
 * (kernel/task.c) может прервать ЛЮБУЮ задачу таймером в произвольный
 * момент независимо от архитектуры драйвера карты, так что то же самое
 * net_irq_save()/net_irq_restore() (те же cli/sti) вокруг кольцевого
 * буфера остаётся нужным само по себе, не только "на всякий случай ради
 * будущего IRQ-контекста". Плюс sem_post() для пробуждения ждущего
 * потребителя -- semaphore_t сам оборачивает свою критическую секцию в
 * cli/sti (см. kernel/sync.c), поэтому вызывать sem_post() из настоящего
 * IRQ можно безопасно, ровно как уже делает kernel/irqbridge.c (это и
 * остаётся верным для ЛЮБОГО будущего вызывающего, даже если сегодня им
 * больше никто не пользуется). Если очередь полна -- кадр отбрасывается
 * (возврат FALSE), а не блокирует вызывающего: то же самое произошло бы
 * и с настоящим кадром при реальной перегрузке сетевой карты, так что
 * это не новая деградация поведения.
 *
 * RX (драйвер-контейнер -> ядро, "вот кадр, который пришёл"): производитель
 * -- обычный ring-3 syscall (SYS_NETBRIDGE_RX_ENQUEUE), потребитель --
 * отдельный поток ядра (netbridge_rx_pump() ниже, task_create() в
 * kernel/kernel.c), который блокирующе ждёт кадры и передаёт их в
 * eth_input() -- то есть замена того, что сейчас делает
 * rtl8139_irq_handler() напрямую. И производитель, и потребитель здесь
 * -- обычный task-контекст (не обработчик прерывания), поэтому
 * блокировка safe в обе стороны; тем не менее push тоже сделан
 * неблокирующим (drop-if-full) -- для единообразия с TX и потому что
 * тот же принцип "лучше потерять кадр, чем зависнуть" уместен и здесь.
 *
 * ---- Подшаг 4.4: канал подключён к настоящему трафику ----
 *
 * eth_send() (net/eth.c) зовёт netbridge_push_tx_frame() вместо прямого
 * доступа к железу, а netbridge_rx_pump() (kernel/kernel.c: отдельный
 * поток ядра) -- единственный потребитель RX-очереди, вызывающий
 * eth_input() для всего, что туда попадёт. Единственный сегодняшний
 * производитель TX-очереди/потребитель RX-очереди с ЭТОЙ стороны моста --
 * apps/rtl8139d.c: обычный ring-3 контейнер, который читает/пишет
 * регистры карты через CAP_IO, ждёт IRQ через CAP_IRQ и вызывает ровно
 * sys_netbridge_tx_dequeue()/sys_netbridge_rx_enqueue() -- запускается
 * автоматически при старте (kernel/netdrv.c: netdrv_launch()), не
 * вручную через shell. Канал при этом остаётся полностью пригоден и для
 * ручной проверки безо всякого железа -- см. shell-команду 'nbtest' и
 * apps/netdrv_echo.c (rootfs/containers/README.txt, Фаза 4, подшаг 3):
 * eth_input() устойчив к мусору (проверяет len < ETH_HDR_LEN, см.
 * net/eth.c), так что подсунуть в RX-очередь что угодно, не только
 * настоящий Ethernet-кадр, по-прежнему безопасно. */

#define NETBRIDGE_MAX_FRAME 1514u /* == RTL_MAX_FRAME в apps/rtl8139d.c, продублировано
    намеренно: этот мост не должен знать про конкретную карту (тот же
    принцип независимости, что и у net.h/eth.h от любой конкретной
    модели) -- если завтра появится вторая карта с другим MTU, у неё
    будет свой драйвер-контейнер, использующий тот же канал с тем же
    пределом. */
#define NETBRIDGE_QUEUE_SLOTS 16u /* столько же, сколько MQ_MAX_MSGS у обычных mqueue -- разумный запас на всплеск, не подобранный под что-то конкретное */

/* Вызывается один раз при старте ядра (kernel/kernel.c), после
   net_init() -- заводит обе очереди (TX и RX) пустыми. Не зависит от
   того, найдена ли физически сетевая карта: сам канал -- инфраструктура,
   годная и для проверки (см. apps/netdrv_echo.c), даже когда её ещё не
   использует ни один настоящий драйвер. */
void netbridge_init(void);

/* ---- API для ядра (сетевой стек, Фаза 4.4) ---- */

/* Кладёт кадр в TX-очередь (ядро -> драйвер-контейнер). Неблокирующая:
   FALSE, если len == 0/len > NETBRIDGE_MAX_FRAME (ошибка аргумента) ЛИБО
   очередь уже полна (кадр отброшен -- диагностика тем же принципом, что
   и у rtl8139_send() при таймауте: сеть теряет кадры, это нормально).
   Безопасна для вызова из НАСТОЯЩЕГО обработчика прерывания -- см. общий
   комментарий выше. */
bool_t netbridge_push_tx_frame(const void *frame, u32 len);

/* Бесконечный цикл: блокирующе забирает кадры из RX-очереди (драйвер-контейнер
   -> ядро) и передаёт каждый в eth_input() (net/eth.c). Сигнатура
   совпадает с task_entry_t (include/task.h) -- предназначена для
   отдельного потока ядра, см. task_create("netbridge-rx", netbridge_rx_pump, 0)
   в kernel/kernel.c. Не возвращается. */
void netbridge_rx_pump(void *arg);

/* ---- API для диспетчера syscall'ов (kernel/syscall.c, требует
   CAP_NET_BRIDGE у вызывающего -- сама проверка капабилити НЕ здесь,
   ровно тот же принцип разделения ответственности, что и у
   irqbridge_wait()/include/irqbridge.h: "механизм" отдельно от
   "проверка прав"). ---- */

/* Блокирует вызывающего до появления кадра в TX-очереди, затем копирует
   его в buf (размера maxlen) и возвращает его длину. <0, если maxlen
   меньше длины кадра (кадр в этом случае теряется, а не остаётся в
   очереди -- в отличие от mq_recv(), т.к. семафор уже "оплачен": см.
   общий комментарий в kernel/netbridge.c про то, почему здесь нельзя
   просто вернуть кадр назад в очередь). Предполагаемый вызывающий --
   драйвер-контейнер с buf размера ровно NETBRIDGE_MAX_FRAME, так что
   этот случай на практике не должен происходить. */
s32 netbridge_sys_tx_dequeue(void *buf, u32 maxlen);

/* Кладёт кадр из buf (длины len) в RX-очередь (драйвер-контейнер ->
   ядро) -- см. netbridge_push_tx_frame() выше за той же неблокирующей
   семантикой. Возвращает 0 при успехе, <0 при ошибке аргумента ИЛИ если
   очередь полна (кадр потерян -- ядро ещё не успело его вычитать). */
s32 netbridge_sys_rx_enqueue(const void *buf, u32 len);

#endif
