#ifndef ISR_H
#define ISR_H

#include "types.h"

/* isr.h -- диспетчер исключений CPU (0-31) и аппаратных прерываний
 * (IRQ 0-15, ремапнутых на векторы 32-47), см. isr.s и pic.h.
 *
 * registers_t -- это точный снимок стека в момент входа в общий
 * ассемблерный обработчик (isr_common_stub/irq_common_stub из isr.s):
 * сначала CPU сам кладёт на стек SS/RSP/RFLAGS/CS/RIP (а для части
 * исключений -- ещё и код ошибки, для остальных мы кладём фиктивный
 * ноль, чтобы стек был одинаковой формы всегда), затем ассемблерная
 * заглушка сохраняет все регистры общего назначения. Поле-за-полем
 * порядок в этой структуре обязан совпадать с порядком push в isr.s --
 * если поменять один без другого, обработчик будет читать мусор.
 */
typedef struct __attribute__((packed)) {
    u64 r15, r14, r13, r12, r11, r10, r9, r8;
    u64 rbp, rdi, rsi, rdx, rcx, rbx, rax;
    u64 int_no, err_code;
    u64 rip, cs, rflags, rsp, ss;
} registers_t;

typedef void (*isr_handler_t)(registers_t *regs);

/* Таблица из 48 адресов (isr0..isr31, irq0..irq15), определена в isr.s.
   Используется idt.c для заполнения IDT -- каждый вектор указывает
   прямо на свою маленькую ассемблерную заглушку. */
extern void *isr_stub_table[48];

/* Регистрирует обработчик конкретного исключения CPU (0-31). Если для
   вектора обработчик не зарегистрирован, isr_handler() выводит
   диагностику и останавливает систему (см. isr.c) -- в отличие от IRQ,
   необработанное исключение почти всегда означает баг ядра, а не
   штатную ситуацию, которую можно просто проигнорировать. */
void isr_register_handler(u8 num, isr_handler_t handler);

/* Регистрирует встроенные обработчики исключений самого ядра (сейчас --
   только #PF, см. kernel/isr.c: page_fault_handler(), include/paging.h).
   Вызывается один раз при старте, после idt_init() и до sti (см.
   kernel/kernel.c) -- обязательно ДО того, как в системе появится
   первая процессная задача, иначе её #PF попадёт в generic-путь. */
void isr_init(void);

/* Регистрирует обработчик аппаратного прерывания (IRQ 0-15, т.е. вектор
   irq+32). EOI на PIC отправляется диспетчером автоматически до вызова
   обработчика (см. isr.c) -- это важно для таймера: его обработчик
   может выполнить переключение задачи и не "вернуться" обычным образом
   ещё долго, поэтому EOI нельзя откладывать на потом. */
void irq_register_handler(u8 irq, isr_handler_t handler);

/* Возвращает TRUE, если для этой IRQ-линии (0-15) уже зарегистрирован
   КАКОЙ-ЛИБО обработчик (через irq_register_handler() выше) -- FALSE
   для линии >= 16 или без обработчика. Используется мостом IRQ->user-space
   (kernel/irqbridge.c, Фаза 4 подшаг 2, см. CONTAINER_ARCHITECTURE.md),
   чтобы не перехватить линию, которой уже владеет драйвер ядра (таймер
   -- IRQ0, сетевая карта и т.п.) -- само по себе it НЕ проверяет
   капабилити/манифест, это забота вызывающего (sys_irq_wait(),
   kernel/syscall.c). */
bool_t irq_handler_is_registered(u8 irq);

/* Вызываются из isr_common_stub/irq_common_stub (isr.s) -- не предназначены
   для прямого вызова из остального кода ядра. */
void isr_handler(registers_t *regs);
void irq_handler(registers_t *regs);

/* Заглушка вектора 0x80 (isr.s) -- отдельно от isr_stub_table, т.к. это
   не исключение CPU и не IRQ, а программное прерывание с DPL=3 (см.
   include/idt.h, IDT_GATE_INTERRUPT_USER), регистрируется отдельно из
   kernel/syscall.c. */
extern void isr128(void);

#endif
