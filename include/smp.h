#ifndef SMP_H
#define SMP_H

#include "types.h"
#include "percpu.h"

/* smp.h -- поднятие дополнительных ядер (Application Processors, AP) и
 * межпроцессорные вызовы поверх них.
 *
 * Общая картина (см. подробности в комментариях конкретных файлов):
 *   1. acpi_find_cpus() (include/acpi.h) читает из ACPI MADT список
 *      физических APIC ID всех ядер, которые видит прошивка;
 *   2. smp_init() копирует трамплин (boot/ap_trampoline.s, встроен в
 *      образ ядра как байтовый массив -- см. Makefile: правило для
 *      build/ap_trampoline.bin + kernel/ap_trampoline_blob.s) в
 *      физическую память по адресу AP_TRAMPOLINE_BASE и последовательно
 *      (см. общий комментарий у smp_start_ap() ниже -- НЕ параллельно)
 *      поднимает каждое ядро, кроме себя самого (BSP уже работает --
 *      это тот процессор, что выполнял GRUB'овский _start);
 *   3. каждый поднятый AP заканчивает путь в ap_entry64() (kernel/smp.c)
 *      -- обычной 64-битной Си-функции, которая доводит инициализацию
 *      этого конкретного ядра (percpu, GDT/TSS, IDT, LAPIC + его
 *      локальный таймер) и передаёт управление планировщику (см.
 *      include/task.h), полностью аналогично тому, что kernel_main()
 *      (kernel/kernel.c) делает для BSP.
 *
 * ВАЖНО о том, чего здесь НЕТ: это ядро не строит per-CPU очереди
 * готовых задач -- все ядра (BSP и все AP) конкурируют за ОДНУ общую
 * очередь планировщика (тот же кольцевой список, что и раньше, см.
 * kernel/task.c), теперь защищённую настоящим спинлоком (include/spinlock.h)
 * вместо одного лишь cli/sti. Это самый простой корректный SMP-планировщик
 * (single run queue) -- он не масштабируется идеально на много десятков
 * ядер (одна общая блокировка становится узким местом), но для учебной ОС
 * с несколькими ядрами это осознанный и куда менее рискованный выбор,
 * чем сразу браться за балансировку нагрузки между персональными
 * очередями -- см. итоговый комментарий в конце kernel/task.c. */

#define AP_TRAMPOLINE_BASE   0x8000u
#define AP_TRAMPOLINE_VECTOR 0x08u   /* AP_TRAMPOLINE_BASE / 0x1000, см. lapic_send_sipi() */
#define AP_TRAMPOLINE_SIZE   0x1000u /* см. build/ap_trampoline.bin -- ровно одна страница */

/* Смещение и раскладка "почтового ящика" внутри трамплина -- ОБЯЗАНЫ
   совпадать один-в-один с хвостом boot/ap_trampoline.s. Плоский бинарник
   не несёт наружу таблицы символов, поэтому адреса этих четырёх полей
   вычисляются арифметически (AP_TRAMPOLINE_BASE + смещение), а не через
   имя метки, как это было бы для обычного .o. */
#define AP_MAILBOX_OFFSET       0x0FE0u
#define AP_MAILBOX_PML4_OFF     0x00u  /* u64: физический адрес PML4 (общий для всех AP) */
#define AP_MAILBOX_STACK_OFF    0x08u  /* u64: вершина стека ЭТОГО конкретного AP */
#define AP_MAILBOX_ENTRY_OFF    0x10u  /* u64: адрес ap_entry64 (общий для всех AP) */
#define AP_MAILBOX_CPUIDX_OFF   0x18u  /* u64 (используются младшие 32 бита): cpu_index этого AP */

/* Обнаруживает остальные ядра через ACPI (include/acpi.h) и поднимает их
   одно за другим (см. smp_start_ap() ниже). Если ACPI недоступен или
   нашёл только одно ядро (само BSP), тихо завершается -- система
   продолжает работать на одном процессоре ровно как до этого файла,
   никакой деградации функциональности. Вызывается один раз из
   kernel_main() (kernel/kernel.c), ПОСЛЕ tasking_init() (нужен
   планировщик, чтобы у AP было на чём выполняться) и ПОСЛЕ
   timer_init() (нужна откалиброванная частота PIT, см.
   lapic_timer_calibrate() в kernel/apic.c), но до долгого пребывания в
   shell'е. */
void smp_init(void);

/* Общее число ядер, успешно поднятых smp_init() (включая сам BSP) --
   удобная обёртка над percpu_online_count() для остального кода (команда
   shell'а 'cpus' и подобное диагностика). */
u32 smp_cpu_count(void);

/* ---- межпроцессорные вызовы (IPI) поверх уже поднятых ядер ---- */

/* Будит все ОСТАЛЬНЫЕ ядра широковещательным IPI вектора
   LAPIC_IPI_RESCHEDULE (include/apic.h) -- каждое из них при получении
   просто возвращается из прерывания (см. kernel/smp_isr.s), ничего
   специально не проверяя: само прерывание уже прерывает HLT в простое
   ядра (см. ap_idle_loop() в kernel/smp.c) и гарантирует, что на
   следующем же обороте цикла оно снова заглянет в общую очередь
   планировщика -- ровно то, что нужно, когда какая-то задача становится
   READY (см. task_wake() в kernel/task.c) и теоретически могла бы
   выполниться НЕМЕДЛЕННО на простаивающем ядре, а не только когда до
   него в следующий раз дотянется его собственный локальный таймер
   (см. lapic_timer_start_periodic() в kernel/apic.c -- в худшем случае
   задержка была бы до одного периода таймера, обычно ~10 мс). */
void smp_kick_idle_cpus(void);

#endif
