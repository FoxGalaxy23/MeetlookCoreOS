#ifndef PAGING_H
#define PAGING_H

#include "types.h"

/* paging.h -- настоящая виртуальная память: у каждого процесса теперь
 * СВОЙ набор таблиц страниц (CR3), а не общий на всю систему.
 *
 * Модель:
 *   - boot/boot.s по-прежнему строит один-единственный identity map
 *     нижних 4 GiB на этапе загрузки -- это "ядерное" адресное
 *     пространство (используется задачами-потоками ядра, у которых
 *     task_t::as == 0, см. include/task.h);
 *   - при создании процесса (as_create(), kernel/process.c) строится
 *     НОВЫЙ набор PML4/PDPT/PD0, куда копируются (по значению) все
 *     записи из ядерного шаблона -- то есть ядро, драйверы, куча ядра
 *     остаются видны из любого процесса ровно как раньше, независимо от
 *     того, чьё CR3 сейчас загружено;
 *   - только 5 конкретных 2 MiB PDE-слотов PD0 (см. include/memlayout.h:
 *     код, стек, куча процесса) в приватной копии заменяются на
 *     ПРИВАТНЫЕ таблицы (PT, 4 KiB PTE) -- вот это и есть настоящее
 *     отдельное адресное пространство процесса;
 *   - fork() (as_clone_cow()) не копирует физическую память немедленно:
 *     присутствующие страницы src помечаются read-only + COW (см.
 *     PTE_COW) в ОБОИХ адресных пространствах, физический кадр
 *     становится общим (refcount++, см. include/pmm.h). Реальное
 *     копирование происходит лениво, из обработчика #PF, в момент
 *     первой записи (см. paging_handle_page_fault());
 *   - тот же обработчик #PF отвечает за "подкачку" (lazy mapping):
 *     страницы кучи и стека процесса физически не существуют, пока в
 *     них не обратятся хотя бы раз -- ровно так растут стек (вниз, до
 *     PROC_STACK_SIZE) и куча (вверх, до PROC_HEAP_SIZE) "по требованию".
 *
 * W^X (см. PTE_NX ниже, kernel/paging.c): ни одна страница процесса
 * никогда не бывает одновременно writable И исполняемой.
 *   - код (PT_LOAD-сегменты ELF, см. kernel/loader.c: elf_load()) --
 *     writable, только если сегмент сам просит PF_W (обычно нет, кроме
 *     .data/.bss-сегментов) -- и, независимо от writable, ВСЕГДА без NX,
 *     только если сегмент просит PF_X, иначе NX;
 *   - стек, куча, argv-страница (все растущие "по требованию" регионы,
 *     см. paging_handle_page_fault() и build_argv() в kernel/process.c)
 *     -- всегда writable + всегда NX: программе никогда не нужно
 *     исполнять то, что лежит в её собственном стеке или куче, а вот
 *     эксплойтам, которые туда что-то записали, это было бы очень нужно;
 *   - разделяемая память (PROC_SHM_BASE) -- всегда NX независимо от
 *     writable: у нескольких процессов нет причин исполнять код прямо
 *     оттуда, а вот шанс, что кто-то туда что-то запишет и передаст
 *     исполнение -- ровно тот сценарий, который W^X и призван исключить.
 */

typedef struct address_space address_space_t;

#define PTE_PRESENT  (1ULL << 0)
#define PTE_WRITABLE (1ULL << 1)
#define PTE_USER     (1ULL << 2)
#define PTE_PS       (1ULL << 7)
/* Бит 9 -- один из трёх AVL-битов, архитектурно отданных ОС на
   произвольное использование (Intel SDM Vol.3 §4.5) -- используем его,
   чтобы отличить "страница временно read-only, потому что она общая с
   другим процессом после fork()" от постоянного read-only. */
#define PTE_COW      (1ULL << 9)
/* NX (No-Execute, он же XD в терминах Intel) -- бит 63, доступен только
   если поддержан CPU (CPUID.80000001H:EDX[20]) И явно включён в
   EFER.NXE (см. enable_nx_if_supported() в kernel/paging.c) -- иначе
   само наличие единицы в этом бите для CPU просто reserved и любое
   обращение к странице с таким PTE даёт #PF с RSVD=1, а не "тихо"
   игнорируется. Поэтому код paging.c ВСЕГДА проверяет g_nx_supported
   перед тем, как выставить этот бит хоть где-то -- см. комментарий там
   же. Если NX не поддержан (редкость для x86_64 в 2020-х, но
   теоретически возможно), W^X попросту не применяется -- страницы
   остаются писать-и-исполнять как раньше, деградация тихая и
   безопасная, а не отказ загрузки. */
#define PTE_NX       (1ULL << 63)

/* Маска для извлечения "чистого" физического адреса кадра ИЗ ЛИСТОВОГО
   PTE (то есть записи, которая непосредственно отображает страницу
   памяти, а не указывает на следующий уровень таблиц трансляции).
   ВАЖНО: `& ~0xFFFull` (маска, которую этот файл исторически применял
   почти везде) снимает только младшие 12 бит (PTE_PRESENT/WRITABLE/
   USER/COW/...) -- этого достаточно для записей PML4E/PDPTE/PDE,
   указывающих на СЛЕДУЮЩУЮ таблицу (они у нас никогда не получают
   PTE_NX), но НЕДОСТАТОЧНО для листовых PTE обычных (writable, то есть
   потенциально NX) страниц данных/кучи/стека: paging_handle_page_fault()
   ниже помечает КАЖДУЮ свежую страницу кучи/стека битом PTE_NX (63-й
   бит), если NX поддержан CPU (g_nx_supported) -- а `~0xFFFull` этот
   бит не трогает. Итог: "физический адрес", полученный так из листового
   PTE, на самом деле оставался тем самым PTE со всё ещё выставленным
   63-м битом -- то есть НЕ настоящим физическим адресом, а числом вида
   0x8000000000XXXXXX. Использование такого "адреса" напрямую как
   указателя (через memcpy() при копировании страницы для COW, через
   pmm_frame_release()/pmm_frame_addref() при подсчёте владельцев кадра)
   давало #GP (адрес неканоничен) при первом же fork() с последующей
   попыткой записи в COW-страницу -- то есть при ЛЮБОМ использовании
   fork() почти любой программой, поскольку stack/heap-страницы
   NX-помечены практически всегда. См. использования ниже (as_map_frame,
   as_clone_cow, as_unmap_range, paging_handle_page_fault). */
#define PTE_ADDR_MASK 0x000FFFFFFFFFF000ULL

/* Биты кода ошибки #PF (Intel SDM Vol.3 §4.7, таблица 4-13). */
#define PF_ERR_PRESENT (1u << 0)  /* 1 = нарушение прав на существующей странице, 0 = страницы вообще нет */
#define PF_ERR_WRITE   (1u << 1)  /* 1 = это была запись */
#define PF_ERR_USER    (1u << 2)  /* 1 = CPL был 3 в момент обращения */

/* Готовит подсистему: запоминает текущие (построенные boot.s) PML4/
   PDPT/PD0 как "ядерный шаблон" для as_create()/as_clone_cow(). Должна
   быть вызвана один раз, рано при старте (до первого as_create()), см.
   kernel/kernel.c. Ничего не меняет в уже включённых таблицах. */
void paging_init(void);

/* Строит новое адресное пространство: ядро/identity map видны сразу
   (скопированы из шаблона), а под код/стек/кучу процесса приватные PT
   выделяются лениво, по мере реальных отображений (см. ниже).
   Возвращает 0 при нехватке памяти. */
address_space_t *as_create(void);

/* Освобождает все физические кадры, на которые адресное пространство
   ссылается (с учётом общих COW-кадров), и сами таблицы страниц. НЕЛЬЗЯ
   вызывать для адресного пространства, которое прямо сейчас загружено в
   CR3 -- в MeetlookCoreOS это гарантируется тем, что уничтожение всегда
   происходит из планировщика для уже переключённой ЧУЖОЙ задачи (см.
   kernel/task.c). */
void as_destroy(address_space_t *as);

/* fork(): создаёт клон src -- те же данные, но с copy-on-write. Все
   присутствующие пользовательские страницы src помечаются read-only
   (если ещё не были) + COW в ОБОИХ адресных пространствах, физический
   кадр становится общим (refcount++). Возвращает 0 при нехватке
   памяти. */
address_space_t *as_clone_cow(address_space_t *src);

/* Выделяет свежий физический кадр, обнуляет его и отображает по адресу
   vaddr (должен попадать в один из PROC_*-регионов, include/memlayout.h)
   как present+user(+writable, если writable==TRUE), без COW. executable
   управляет NX-битом (см. PTE_NX выше): FALSE -- страница НЕ может быть
   исполнена (обычные данные/куча/стек), TRUE -- может (только код,
   PF_X-сегменты ELF, см. kernel/loader.c). Комбинация writable=TRUE +
   executable=TRUE НЕ запрещена на уровне этой функции физически (CPU
   такое тоже допускает), но ни один вызывающий код в этой системе так
   не делает -- см. W^X-комментарий в начале kernel/paging.c. Возвращает
   указатель на кадр (он же его физический адрес -- вся физическая
   память identity-mapped из ядра), пригодный для немедленной записи из
   ядра (например, чтобы скопировать туда код бинарника) -- независимо
   от того, чьё CR3 сейчас загружено. Возвращает 0 при нехватке памяти
   или если vaddr вне известных PROC_*-регионов. */
void *as_alloc_and_map(address_space_t *as, u64 vaddr, bool_t writable, bool_t executable);

/* Низкоуровневая версия: отображает УЖЕ имеющийся физический кадр paddr
   по адресу vaddr с заданными правами -- используется as_clone_cow()
   (общий кадр на двоих) и paging_handle_page_fault() (после копирования
   при разрешении COW). executable -- см. as_alloc_and_map() выше. Не
   трогает refcount кадра -- вызывающий код обязан сам заранее вызвать
   pmm_frame_addref(), если это требуется. */
bool_t as_map_frame(address_space_t *as, u64 vaddr, u64 paddr, bool_t writable, bool_t executable, bool_t cow);

/* Загружает CR3 адресного пространства as (as == 0 означает "ядерное"
   адресное пространство -- то, что построил boot.s), если оно ещё не
   загружено. Дешёвая операция при повторных вызовах с тем же as.
   Вызывается из планировщика (kernel/task.c) при каждом переключении
   задачи. */
void paging_switch(address_space_t *as);

/* Физический адрес "ядерного" PML4 (см. kernel/paging.c) -- нужен
   AP-трамплину при подъёме дополнительных ядер, см. include/smp.h. */
u64 paging_kernel_cr3(void);

/* Текущее значение CR2 (адрес, на котором случился последний #PF). */
u64 paging_read_cr2(void);

/* Основной обработчик #PF для пользовательских адресных пространств.
 * as -- адресное пространство ТЕКУЩЕЙ задачи (task_current()->as); если
 * as == 0 (это поток ядра, а не процесс), функция ничего не делает и
 * сразу возвращает FALSE -- вызывающий код (kernel/isr.c) обязан считать
 * это багом ядра.
 *
 * Возвращает TRUE, если состояние исправлено и можно просто повторить
 * упавшую инструкцию (страница подкачана: рост кучи/стека, либо
 * разрешён COW: страница скопирована и стала writable).
 *
 * Возвращает FALSE, если адрес/причина не подходят ни под один из
 * известных случаев (реальный segfault) -- виновата САМА программа, и
 * вызывающий код обязан завершить только её (process_exit()), не трогая
 * систему в целом. */
bool_t paging_handle_page_fault(address_space_t *as, u64 fault_vaddr, u64 error_code);

/* TRUE, если весь диапазон [ptr, ptr+len) целиком лежит внутри одного
   из отведённых процессу регионов. Для кода/стека/кучи -- по их
   МАКСИМАЛЬНОЙ зарезервированной величине, а не только уже реально
   подкачанной части (страницы могут появиться позже, лениво, через
   #PF). Для окна разделяемой памяти (PROC_SHM_BASE, include/memlayout.h)
   -- иначе: там лениво ничего не появляется, поэтому диапазон обязан
   быть УЖЕ реально отображён (см. kernel/ipc.c: shm_attach()), а не
   просто попадать в максимальный размер окна. Используется
   kernel/uaccess.c. len == 0 всегда допустим. */
bool_t as_range_is_user_accessible(const address_space_t *as, u64 start, u32 len);

/* Снимает отображение диапазона [vaddr, vaddr+len) в адресном
   пространстве as: для каждой присутствующей страницы -- очищает PTE,
   делает invlpg и вызывает pmm_frame_release() (т.е. корректно снимает
   ровно одну ссылку на физический кадр, симметрично тому, что делали
   as_map_frame()/pmm_frame_addref() при отображении). Страницы, которых
   и не было (not present), просто пропускаются. Используется
   kernel/ipc.c для явного shm_detach() ЖИВОГО процесса -- в отличие от
   отображений, которые снимаются целиком при завершении задачи (см.
   as_destroy() в kernel/task.c), здесь процесс продолжает работать, и
   диапазон должен перестать быть доступен именно сейчас, а не только
   когда-нибудь при уничтожении всего адресного пространства. vaddr/len
   не обязаны быть выровнены по границе страницы -- округляются наружу
   до целых страниц. Не проверяет принадлежность диапазона какому-то
   конкретному региону -- это дело вызывающего кода (ipc.c уже знает
   границы своего сегмента). */
void as_unmap_range(address_space_t *as, u64 vaddr, u32 len);

#endif
