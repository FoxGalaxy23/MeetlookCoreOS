#ifndef SYNC_H
#define SYNC_H

#include "types.h"
#include "task.h"
#include "spinlock.h"

/* sync.h -- примитивы синхронизации поверх планировщика (см. task.h).
 *
 * До этого файла TASK_BLOCKED существовал только как значение enum:
 * ничто не переводило задачу в это состояние и ничто её не будило --
 * единственный способ уступить процессор был task_yield() (чистая
 * кооперативная вежливость, не ожидание конкретного события). Теперь,
 * когда планировщик умеет вытеснять задачи по-настоящему (см. task.c:
 * scheduler_tick()/schedule()), это стало проблемой: два потока ядра,
 * работающие с общими данными, могут быть прерваны ДРУГ ДРУГОМ ровно
 * посреди критической секции.
 *
 * Все примитивы здесь построены на одном и том же фундаменте --
 * waitqueue_t (односвязный список заблокированных task_t, через поле
 * task_t::wq_next) и паре task_block_self()/task_wake() из task.c:
 *
 *   - заблокироваться значит: захватить собственный спинлок объекта,
 *     встать в waitqueue_t, ОТПУСТИТЬ спинлок, вызвать task_block_self();
 *   - разбудить значит: под тем же спинлоком снять задачу с waitqueue_t,
 *     вызвать task_wake().
 *
 * SMP (см. include/smp.h за общей картиной): раньше система была
 * однопроцессорной, и одного отключения прерываний (cli/sti) хватало
 * для атомарности -- пока прерывания выключены, ничто другое на
 * единственном CPU не выполняется. Теперь ядер может быть несколько, и
 * cli на одном ядре никак не мешает другому ядру одновременно попасть в
 * тот же mutex_lock()/sem_post() -- отсюда собственный spinlock_t
 * (include/spinlock.h) в каждом mutex_t/semaphore_t/condvar_t: он
 * защищает СОБСТВЕННОЕ состояние объекта (locked/count/waiters) от
 * одновременного доступа с других ядер, а cli по-прежнему защищает от
 * таймерного вытеснения НА ЭТОМ ядре посреди критической секции.
 *
 * ВАЖНО (тот же принцип, что у самого спинлока, см. include/spinlock.h):
 * спинлок объекта ОБЯЗАН быть отпущен ДО task_block_self() -- иначе
 * задача, которая должна была бы разбудить нас через mutex_unlock()/
 * sem_post()/cond_signal(), просто не смогла бы захватить тот же самый
 * спинлок (мы же не отдаём его, будучи заблокированными) -- classic
 * deadlock, тот же самый, что описан для g_sched_lock в kernel/task.c.
 * Именно поэтому в реализациях ниже (kernel/sync.c) спинлок отпускается
 * ПЕРЕД task_block_self() и захватывается заново ПОСЛЕ пробуждения, для
 * повторной проверки условия в цикле.
 *
 * ВАЖНО: ни один из этих примитивов нельзя использовать из самого
 * обработчика прерывания (в т.ч. из timer_irq_handler) -- блокировка
 * там означала бы заблокировать прерывания вообще, а не конкретную
 * задачу, и до места, которое должно её разбудить, управление могло
 * бы просто никогда не дойти. Они рассчитаны на обычный код задач
 * (потоков ядра), выполняющийся с разрешёнными прерываниями. */

typedef struct waitqueue {
    task_t *head;
    task_t *tail;
} waitqueue_t;

/* ---- мьютекс: взаимное исключение, владение конкретной задачей ---- */

typedef struct mutex {
    spinlock_t lock;      /* защищает поля ниже от одновременного доступа с других ядер (см. выше) */
    bool_t locked;
    task_t *owner;       /* для диагностики и проверки owner == task_current() в unlock */
    waitqueue_t waiters;
} mutex_t;

void mutex_init(mutex_t *m);

/* Блокирует вызывающего, если мьютекс уже занят, пока не освободится.
   Рекурсивный захват (тот же owner повторно) НЕ поддерживается --
   приведёт к самоблокировке (задача будет ждать сама себя). */
void mutex_lock(mutex_t *m);

/* Пытается захватить без блокировки. Возвращает TRUE при успехе. */
bool_t mutex_trylock(mutex_t *m);

/* Освобождает мьютекс и будит одну ожидающую задачу (если есть) --
   она не получает лок "в подарок", а просто становится READY и
   заново конкурирует за него в своём mutex_lock() наравне со всеми:
   простой (не строго FIFO), но корректный дизайн. Вызывающий обязан
   быть текущим владельцем -- вызов для чужого/незанятого мьютекса
   является багом вызывающего кода. */
void mutex_unlock(mutex_t *m);

/* ---- семафор: счётчик доступных "ресурсов" ---- */

typedef struct semaphore {
    spinlock_t lock;
    s32 count;
    waitqueue_t waiters;
} semaphore_t;

void sem_init(semaphore_t *s, s32 initial_count);

/* P() / acquire / wait: блокирует, пока count <= 0, затем декрементирует. */
void sem_wait(semaphore_t *s);

/* Не блокирующая версия sem_wait(). Возвращает TRUE и декрементирует,
   если ресурс был доступен сразу, иначе FALSE и count не трогает. */
bool_t sem_trywait(semaphore_t *s);

/* V() / release / post: инкрементирует count и будит одну ожидающую
   задачу (если есть). Можно вызывать и без предварительного wait
   (например, чтобы "подарить" ресурс) -- в этом смысле семафор, в
   отличие от мьютекса, не привязан к понятию владельца. */
void sem_post(semaphore_t *s);

/* ---- условная переменная: ожидание условия под чужим мьютексом ---- */

typedef struct condvar {
    spinlock_t lock;
    waitqueue_t waiters;
} condvar_t;

void cond_init(condvar_t *c);

/* Классическая семантика: атомарно (относительно cond_signal/broadcast
   на этой же системе -- см. общий комментарий выше про однопроцессорность)
   освобождает m, засыпает в очереди condvar-а, а после пробуждения
   заново захватывает m ПЕРЕД тем, как вернуть управление вызывающему.
   Вызывающий обязан держать m захваченным на входе; m остаётся
   захваченным и на выходе. Как и везде в pthread-подобных condvar,
   вызывающий должен перепроверять своё условие в цикле после
   возврата -- пробуждение не гарантирует, что условие всё ещё(!)
   истинно (classic spurious/racing wakeup со стороны других
   ожидающих, успевших забрать ресурс первыми). */
void cond_wait(condvar_t *c, mutex_t *m);

/* Будит ровно одну ожидающую задачу (если есть). Не требует держать
   связанный мьютекс захваченным на момент вызова (хотя это и обычная
   практика в pthread-стиле, чтобы не потерять пробуждение между
   проверкой условия и cond_wait соседа) -- см. общий комментарий про
   отключение прерываний как единственную реально нужную здесь защиту. */
void cond_signal(condvar_t *c);

/* Будит ВСЕ ожидающие задачи. */
void cond_broadcast(condvar_t *c);

#endif
