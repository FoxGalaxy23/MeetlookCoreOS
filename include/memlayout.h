#ifndef MEMLAYOUT_H
#define MEMLAYOUT_H

/* memlayout.h -- разметка виртуального адресного пространства ОДНОГО
 * процесса (одинакова для всех процессов -- это ОДНИ И ТЕ ЖЕ виртуальные
 * адреса в каждом per-process наборе таблиц страниц, см. kernel/paging.c).
 *
 * Всё это лежит внутри первого 1 GiB (GB0), т.к. per-process приватность
 * реализована точечно: PD0 (Page Directory нулевого PDPT-элемента)
 * приватен для каждого процесса и содержит 2 MiB PDE-слоты; ровно 6 из
 * 512 таких слотов (индексы 3..8, см. *_SLOT ниже) заменены на приватные
 * PT (4 KiB PTE) вместо обычных 2 MiB huge pages -- именно они и образуют
 * "окно" процесса (код/стек/куча -- индексы 3..7, разделяемая память
 * IPC -- индекс 8, см. PROC_SHM_BASE ниже). Все остальные PDE (низкий
 * 1 MiB, образ ядра, куча ядра и т.д.) -- общие для всех процессов копии
 * одного и того же шаблона
 * (см. paging_init()/as_create() в kernel/paging.c), поэтому ядро видит
 * одну и ту же память независимо от того, чьи таблицы сейчас в CR3.
 *
 * Значения ниже НАМЕРЕННО совпадают с APP_LOAD_ADDR/APP_MAX_SIZE
 * (include/loader.h) и старыми USER_STACK_ADDR/USER_STACK_SIZE
 * (историческая версия -- include/usermode.h) -- это те же самые адреса,
 * только теперь за каждым из них при разных CR3 стоят разные физические
 * страницы, а не одна и та же общая память.
 *
 * ВАЖНО: физический диапазон [0x02000000, 0x02C00000) (=[32 MiB,44 MiB),
 * код+стек+куча+shm вместе) зарезервирован в PMM (см. kernel/pmm.c)
 * целиком и никогда не выдаётся обычной куче ядра (kernel/kheap.c:
 * HEAP_START_ADDR = 0x01200000, ровно конец этого окна) -- см.
 * комментарий там же за тем, почему это обязательно (иначе кусок кучи
 * ядра мог бы оказаться физически там, куда per-process PD0 "дырявит"
 * отображение). Сами страницы кода/стека/кучи процесса используют
 * СОВСЕМ ДРУГИЕ физические кадры (обычные, из общего пула
 * pmm_alloc_frame()), отображённые на эти виртуальные адреса через
 * приватные PT -- см. kernel/process.c. */

/* ВАЖНО (баг, найденный и исправленный в Фазе 4.4 -- см. CONTAINER_ARCHITECTURE.md
 * и git-историю этого файла): значения ниже раньше начинались с 6 MiB
 * (PROC_CODE_BASE = 0x00600000) -- разумно на момент, когда это писалось,
 * но с тех пор .bss ядра (g_bitmap, g_refcount, file_data, стек BSP из
 * boot.s и т.д.) выросло и стало ЗАХОДИТЬ на эту границу (kernel_end
 * оказывался БОЛЬШЕ 0x00600000). Из-за этого физическая память, где
 * реально лежит стек BSP (boot.s: stack_bottom/stack_top -- тот самый
 * стек, на котором продолжает работать kernel_main() и всё, что он
 * вызывает напрямую, включая интерактивный shell), попадала ВНУТРЬ этого
 * самого окна -- окна, которое per-process PD0 (см. общий комментарий
 * выше) делает ПРИВАТНЫМ для каждого процесса. Стоило schedule() хоть
 * раз вызвать paging_switch() на РЕАЛЬНЫЙ процесс (а не на другой
 * поток ядра с as=0) ПОКА текущий код всё ещё выполняется на стеке BSP --
 * а именно так и происходит: paging_switch() в kernel/task.c вызывается
 * ДО context_switch(), то есть чужие таблицы страниц уже действуют, а
 * стек ещё старый -- как этот самый стек тут же переставал быть тем, чем
 * был: под чужим CR3 по тем же виртуальным адресам лежат УЖЕ ЧУЖИЕ
 * страницы (код/данные того процесса, на который переключаемся, а не
 * стек ядра). Симптом был воспроизводим на пустом месте (`run hello`,
 * без единого fork()) и выглядел как переход по случайному адресу внутри
 * структуры task_t сразу после успешного context_switch() -- НЕ
 * повреждение данных (проверено канарейками вокруг kmalloc(), см.
 * kernel/kheap.c), а именно чтение/запись через указатель, который под
 * новым CR3 стал указывать совсем не туда.
 *
 * Исправление -- поднять всё окно значительно выше любого разумного
 * будущего размера .bss ядра (запас ~26 MiB на дальнейший рост, а не
 * подгонка впритык под текущий kernel_end, чтобы не наступить на те же
 * грабли снова после ещё нескольких фаз). Стек BSP (boot.s) при этом
 * НЕ трогаем -- он остаётся там, где его положил boot.s (несколько MiB,
 * задача компоновщика), а окно процессов просто больше никогда не будет
 * с ним пересекаться. */

#define PROC_CODE_BASE   0x02000000ull
#define PROC_CODE_SIZE   0x00200000u    /* 2 MiB, ровно один PDE-слот (индекс 16) */

#define PROC_STACK_BASE  0x02200000ull
#define PROC_STACK_SIZE  0x00200000u    /* 2 MiB, ровно один PDE-слот (индекс 17) */

#define PROC_HEAP_BASE   0x02400000ull
#define PROC_HEAP_SIZE   0x00600000u    /* 6 MiB, три PDE-слота (индексы 18,19,20) */

/* Окно разделяемой памяти (см. include/ipc.h, kernel/ipc.c) -- ЕДИНСТВЕННЫЙ
 * per-process регион, который умышленно НЕ следует общей для code/stack/
 * heap модели "приватно + COW при fork()" (см. as_clone_cow() в
 * kernel/paging.c: для этого конкретного слота она мапит кадр как
 * настоящий общий, а не copy-on-write, иначе разделяемая память потеряла
 * бы смысл в тот момент, когда кто-то из процессов, унаследовавших её
 * через fork(), впервые в неё запишет).
 *
 * Одно и то же окно PROC_SHM_BASE..+PROC_SHM_SIZE нарезано на
 * SHM_MAX_SEGMENTS равных кусков (см. include/ipc.h: SHM_SEGMENT_SIZE) --
 * во ВСЕХ процессах один и тот же id сегмента всегда соответствует одному
 * и тому же виртуальному смещению внутри этого окна, поэтому кадры
 * сегмента можно просто мапить по формуле, не храня отдельную таблицу
 * "кто, где и куда" на процесс. Страницы этого региона в отличие от
 * стека/кучи НЕ подкачиваются лениво через #PF -- отображены только
 * реально присоединённые (shm_attach()) сегменты, см. as_range_is_user_accessible()
 * в kernel/paging.c: там для этого слота, в отличие от остальных, дополнительно
 * проверяется, что страницы ДЕЙСТВИТЕЛЬНО присутствуют, а не только что
 * адрес попадает в разрешённый диапазон. */
#define PROC_SHM_BASE    0x02A00000ull
#define PROC_SHM_SIZE    0x00200000u    /* 2 MiB, ровно один PDE-слот (индекс 21) */

/* Первый и последний (не включая) индекс PD0, занятый под приватные
   per-process окна -- используется kernel/paging.c для клонирования/
   уничтожения адресных пространств без необходимости знать про code/
   stack/heap/shm по отдельности. */
#define PROC_FIRST_PD_SLOT 16u
#define PROC_LAST_PD_SLOT  21u   /* включительно; 21 -- окно SHM, см. выше */

#endif
