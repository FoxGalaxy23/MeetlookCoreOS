#ifndef PERCPU_H
#define PERCPU_H

#include "types.h"

/* percpu.h -- данные "на своё ядро" (per-CPU), фундамент SMP наравне со
 * спинлоками (include/spinlock.h) и APIC (include/apic.h).
 *
 * До SMP в системе было ровно одно из всего: один g_current в task.c,
 * один g_tss/g_gdt в gdt.c, один g_current_cr3 в paging.c -- это были
 * попросту "переменные ядра", без разницы, откуда их читают, потому что
 * читать их мог только один-единственный процессор. У каждого ядра
 * теперь должна быть СВОЯ версия: своя текущая задача (два ядра не
 * могут одновременно считать текущей одну и ту же task_t), свой TSS
 * (см. kernel/gdt.c -- TSS.RSP0 у каждого ядра указывает на СВОЙ стек
 * ядра для перехода ring3->ring0, общий TSS означал бы, что второе
 * прерывание из ring3 на другом ядре затрёт RSP0 первого прямо у него
 * из-под ног), своё кэшированное значение CR3 (см. kernel/paging.c --
 * CR3 физически ЛОКАЛЬНЫЙ регистр процессора, а не общий).
 *
 * Механизм доступа: MSR IA32_GS_BASE (0xC0000101) на каждом ядре
 * указывает на СВОЙ собственный percpu_t (см. percpu_init_early() в
 * kernel/percpu.c, вызывается и на BSP, и на каждом AP на самом раннем
 * этапе их инициализации, см. kernel/smp.c). Само значение сегментного
 * регистра GS при этом остаётся плоским нулевым дескриптором (как и
 * было в kernel/gdt.c) -- используется только СКРЫТАЯ база GS,
 * переставленная WRMSR-ом в обход обычной загрузки через селектор.
 * SWAPGS не нужен: в этой системе GS никогда не используется
 * пользовательским (ring 3) кодом ни для чего (syscall'ы идут через
 * `int 0x80`, не через SYSCALL/SYSRET, см. include/syscall.h) -- то
 * есть база GS, однажды выставленная здесь, никогда не подменяется и
 * не восстанавливается кем-либо ещё, и попытки ring3-кода прочитать
 * `%gs`-относительный адрес приводят самое большее к чтению нулевого
 * (селектор всё ещё плоский) сегмента, а не к утечке percpu_t. */

#define SMP_MAX_CPUS 32u

struct task; /* см. include/task.h -- не включаем его сюда, чтобы не тащить
                paging.h/isr.h всюду, где нужен лишь указатель */

typedef struct percpu {
    struct percpu *self;      /* ОБЯЗАН быть первым полем -- см. this_cpu() ниже:
                                  чтение %gs:0 должно сразу дать указатель на
                                  сам этот percpu_t, без дополнительных смещений */
    u32 cpu_index;             /* 0..smp_cpu_count()-1, порядковый номер в порядке обнаружения (см. acpi.h) */
    u32 lapic_id;               /* физический APIC ID этого ядра (см. include/apic.h) */
    bool_t online;               /* TRUE, когда ядро прошло percpu_init_early() и готово планировщику */

    struct task *current_task;   /* задача, выполняющаяся ПРЯМО СЕЙЧАС на этом ядре --
                                     замена одиночного g_current из kernel/task.c */
    struct task *idle_task;       /* "нулевая" задача этого ядра (см. kernel/smp.c: ap_main()) --
                                     то, на чём ядро крутится, когда в общей очереди нечего делать */

    u64 current_cr3;              /* кэш последнего загруженного CR3 НА ЭТОМ ядре --
                                      замена одиночного g_current_cr3 из kernel/paging.c
                                      (см. paging_switch()): CR3 -- честно локальный регистр
                                      процессора, кэшировать его в одной общей переменной для
                                      всех ядер означало бы, что ядро B решит "CR3 уже тот,
                                      что нужен" на основании того, что ядро A когда-то его
                                      уже загрузило -- у СЕБЯ, а не у ядра B. */

    u64 sched_ticks;               /* тиков локального таймера (LAPIC, см. kernel/apic.c) с момента
                                       старта этого ядра -- диагностика (команда shell'а 'cpus') */
    u32 time_slice_ticks;          /* тиков с последнего переключения на ЭТОМ ядре -- замена
                                       одиночного g_tick_counter из kernel/task.c (см. TASK_TIME_SLICE_TICKS,
                                       include/task.h): у каждого ядра своя точка отсчёта кванта времени,
                                       общий счётчик на все ядра просто не имел бы смысла */
} percpu_t;

/* Готовит percpu_t для cpu_index-го ядра (см. g_percpu[] в percpu.c) и
   выставляет MSR IA32_GS_BASE так, чтобы this_cpu() начиная с этого
   момента и на этом самом физическом ядре возвращал указатель именно на
   него. Вызывается РОВНО один раз на КАЖДОМ ядре -- на BSP из
   kernel_main() (см. kernel/kernel.c), на каждом AP -- из его
   собственной ветки ap_main() (см. kernel/smp.c), максимально рано, до
   первого обращения к this_cpu() (в частности, до gdt_init()/
   gdt_init_ap() -- см. include/gdt.h, они читают cpu_index через
   this_cpu(), чтобы понять, чей персональный TSS/GDT готовить). */
void percpu_init_early(u32 cpu_index, u32 lapic_id);

/* Указатель на percpu_t текущего ядра -- читается из скрытой базы GS
   (см. общий комментарий выше), а не через какой-либо глобальный
   массив с явным поиском "а какое я вообще ядро" -- именно поэтому
   вызов дешёвый (одно чтение памяти) и безопасен из любого контекста,
   включая обработчики прерываний. */
static inline percpu_t *this_cpu(void) {
    percpu_t *p;
    __asm__ volatile ("mov %%gs:0, %0" : "=r"(p));
    return p;
}

/* Общее число ядер, для которых уже вызван percpu_init_early() --
   растёт по мере того, как smp_init() (kernel/smp.c) поднимает AP один
   за другим; ДО вызова smp_init() равно 1 (только BSP, см. kernel.c). */
u32 percpu_online_count(void);

/* Перебор по индексу 0..percpu_online_count()-1, для диагностики
   ('cpus' в shell) и для IPI-рассылки по всем известным ядрам (см.
   include/smp.h: smp_send_ipi_all()). Возвращает 0, если индекс вне
   диапазона. */
percpu_t *percpu_get(u32 index);

#endif
