#ifndef KHEAP_H
#define KHEAP_H

#include "types.h"

/* kheap.h -- куча ядра: обычный kmalloc/kfree поверх памяти, уже
 * зарезервированной в PMM (см. include/pmm.h).
 *
 * Модель простая и осознанно не растёт "по требованию": при старте
 * резервируется один непрерывный физический (=виртуальный, вся низкая
 * память identity-mapped) регион фиксированного максимального размера,
 * и дальше это уже классический аллокатор первого подходящего блока
 * (first-fit) со списком блоков, слиянием соседних свободных блоков
 * при освобождении и разбиением блоков при выделении. Расти он не
 * может, зато не нужно ничего домапливать в page table -- честный
 * компромисс для системы без демand paging.
 *
 * Используется и самим ядром, и пользовательскими бинарниками через
 * kapi_t (kmalloc/kfree/kcalloc/krealloc) -- см. include/kapi.h.
 */

void kheap_init(void);

void *kmalloc(u32 size);
void *kcalloc(u32 nmemb, u32 size);
void *krealloc(void *ptr, u32 new_size);
void kfree(void *ptr);

u32 kheap_total_bytes(void);
u32 kheap_used_bytes(void);
u32 kheap_free_bytes(void);

/* ---- Диагностический инструмент (см. большой комментарий в
   kernel/kheap.c про канарейку -- появился при охоте за багом Фазы 4.4,
   найденным и исправленным переносом окна процесса, см.
   include/memlayout.h) ----
   Проходит по ВСЕМ занятым (не free) блокам кучи и проверяет "канарейку"
   -- 16 байт известного паттерна, дописанные СРАЗУ после того, что
   реально запросил вызывающий kmalloc(), ДО следующего блока. Если
   какой-то код записал за границу СВОЕГО выделения, канарейка будет
   испорчена, и это обнаружится здесь -- даже для блока, который ещё
   ни разу не был kfree() (в отличие от обычной проверки только на
   освобождении). tag -- просто метка в kprintf для понимания, ГДЕ по
   коду был вызван этот чек -- полезно расставить по нескольким местам
   и сузить обхватом окно, где произошло повреждение. Возвращает FALSE,
   если нашла хоть одно повреждение (и печатает подробности сама). */
bool_t kheap_check_all(const char *tag);

#endif
