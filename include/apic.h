#ifndef APIC_H
#define APIC_H

#include "types.h"

/* apic.h -- Local APIC (Advanced Programmable Interrupt Controller),
 * встроенный в каждое ядро процессора начиная с P6/Pentium 4 (на
 * многоядерных/многопроцессорных системах -- обязателен, см. Intel SDM
 * Vol.3 гл.10).
 *
 * До этого файла в системе был только 8259 PIC (см. include/pic.h) --
 * его достаточно, чтобы получать IRQ0-15 на ОДНОМ процессоре (том,
 * к которому физически подключены его выходные линии, INTR), но у него
 * попросту нет понятия "какому именно ядру доставить прерывание" и уж
 * тем более нет способа заставить ОДНО ядро прервать ДРУГОЕ -- то есть
 * межпроцессорные прерывания (IPI, Inter-Processor Interrupts). Ровно
 * поэтому SMP немыслим без LAPIC: он даёт (1) IPI -- в т.ч. INIT/SIPI,
 * которыми BSP поднимает AP (см. kernel/smp.c), и обычные "разбуди/
 * перепланируй" IPI между уже работающими ядрами; (2) собственный
 * таймер на каждом ядре -- в отличие от PIT (один физический канал,
 * его прерывание получает только тот, к кому подключен выход PIC),
 * таймер LAPIC -- ЛОКАЛЬНЫЙ регистр процессора, есть у каждого ядра в
 * отдельности, поэтому это единственный способ дать каждому AP
 * собственный периодический "пульс" планировщика (см.
 * timer_irq_handler() в kernel/timer.c -- та же роль, но там это делает
 * общий PIT для BSP).
 *
 * ВАЖНО про сосуществование с PIC: эта система НЕ перепрограммирует
 * маршрутизацию IRQ0-15 через I/O APIC -- BSP по-прежнему получает их
 * ровно как раньше, через 8259 (см. kernel/pic.c, kernel/timer.c). LAPIC
 * включается ДОПОЛНИТЕЛЬНО, в режиме совместимости ("virtual wire
 * compatibility mode", Intel SDM Vol.3 §10.4.7.3): LVT LINT0 в
 * состоянии сброса уже сконфигурирован как ExtINT и не трогается,
 * поэтому путь PIC -> LINT0 -> BSP остаётся рабочим одновременно с
 * включённым LAPIC. Требуется это ТОЛЬКО для того, чтобы вообще
 * слать/принимать IPI и иметь локальный таймер -- маршрутизация
 * существующих устройств (клавиатура, диски, сеть) не меняется и
 * продолжает приходить исключительно на BSP, как и раньше.
 *
 * MMIO: регистры LAPIC отображены на 4 KiB окно физической памяти
 * (обычно 0xFEE00000, см. lapic_base() в apic.c -- читается из
 * IA32_APIC_BASE, а не жёстко зашивается, хотя релокация в реальности
 * почти никогда не встречается). Это попадает в третий GiB (0xC0000000-
 * 0xFFFFFFFF), который boot/boot.s уже отображает identity + PCD
 * (некэшируемо, см. fill_pd_common_uncached) -- отдельно мапить или
 * помечать uncached ничего не нужно, страница уже готова. */

#define LAPIC_REG_ID           0x020u
#define LAPIC_REG_VERSION      0x030u
#define LAPIC_REG_TPR          0x080u
#define LAPIC_REG_EOI          0x0B0u
#define LAPIC_REG_SPURIOUS     0x0F0u
#define LAPIC_REG_ICR_LOW      0x300u
#define LAPIC_REG_ICR_HIGH     0x310u
#define LAPIC_REG_LVT_TIMER    0x320u
#define LAPIC_REG_LVT_LINT0    0x350u
#define LAPIC_REG_LVT_LINT1    0x360u
#define LAPIC_REG_LVT_ERROR    0x370u
#define LAPIC_REG_TIMER_INIT   0x380u
#define LAPIC_REG_TIMER_CUR    0x390u
#define LAPIC_REG_TIMER_DIV    0x3E0u

#define LAPIC_SPURIOUS_VECTOR   0xFFu  /* обычно берут последний вектор страницы (0xF0-0xFF) */
#define LAPIC_TIMER_VECTOR      0xF0u  /* см. kernel/smp_isr.s: ap_timer_stub */
#define LAPIC_IPI_RESCHEDULE    0xFBu  /* см. kernel/smp_isr.s: ipi_reschedule_stub */
#define LAPIC_IPI_CALL          0xFCu  /* см. kernel/smp_isr.s: ipi_call_stub, include/smp.h */

/* Инициализирует LAPIC ТЕКУЩЕГО ядра: гарантирует программный enable
   (бит 8 регистра Spurious Interrupt Vector) и регистрирует вектор
   spurious-прерывания. Обязана быть вызвана на КАЖДОМ ядре отдельно
   (BSP -- из smp_init(), AP -- из ap_main(), см. kernel/smp.c) -- это
   не общесистемная настройка, а свойство конкретного физического
   процессора. */
void lapic_init(void);

/* Физический APIC ID ЭТОГО ядра (регистр LAPIC_REG_ID) -- то, чем ядра
   идентифицируют друг друга при отправке IPI (см. ниже) и что
   сообщает ACPI MADT (см. include/acpi.h) заранее, ДО того, как ядро
   реально запущено. */
u32 lapic_id(void);

/* Сообщает LAPIC, что обработка текущего прерывания завершена --
   аналог pic_send_eoi(), но для векторов, доставленных через LAPIC
   (локальный таймер, IPI), а не через 8259. Обязательна в конце любого
   такого обработчика (см. kernel/smp_isr.s) -- без неё LAPIC решит, что
   ядро всё ещё занято текущим прерыванием, и не пришлёт следующее того
   же класса (Intel SDM Vol.3 §10.8.5). */
void lapic_eoi(void);

/* ---- IPI: INIT/SIPI (bring-up AP, см. kernel/smp.c) ---- */

/* Посылает INIT IPI указанному физическому APIC ID -- переводит целевое
   ядро в состояние "ждёт SIPI" (аналог RESET, но без сброса некоторых
   внутренних состояний -- см. Intel SDM Vol.3 §10.6.4.2). Блокируется
   до подтверждения отправки (не до обработки -- у INIT/SIPI, в отличие
   от обычных IPI, нет аппаратного ACK от получателя, только busy-бит
   отправителя). */
void lapic_send_init(u32 target_apic_id);

/* Посылает Startup IPI (SIPI) -- сообщает целевому AP, с какой
   странице физической памяти (vector * 0x1000, обязана быть < 1 MiB)
   начать выполнение в 16-битном real mode (см. boot/ap_trampoline.s).
   Согласно MP-спецификации SIPI нужно послать ДВАЖДЫ подряд (см.
   smp_start_ap() в kernel/smp.c за точной последовательностью INIT ->
   пауза -> SIPI -> пауза -> SIPI). */
void lapic_send_sipi(u32 target_apic_id, u8 vector);

/* ---- Обычные IPI между уже работающими ядрами ---- */

/* Посылает fixed-IPI (доставляется как обычное прерывание вектора
   `vector` на целевом ядре) конкретному физическому APIC ID. Не ждёт
   обработки на приёмнике -- только отправки (busy-бит ICR). */
void lapic_send_ipi(u32 target_apic_id, u8 vector);

/* То же самое, но всем ядрам, кроме себя (shorthand-поле ICR
   "all excluding self", Intel SDM Vol.3 §10.6.1 табл.10-6) -- не нужно
   заранее знать APIC ID получателей, аппаратура сама рассылает всем,
   кто отвечает на IPI, кроме отправителя. Используется для широковещательных
   reschedule/call-IPI (см. include/smp.h: smp_send_ipi_all()). */
void lapic_send_ipi_broadcast(u8 vector);

/* ---- Локальный таймер (периодический "пульс" планировщика для AP) ---- */

/* Настраивает локальный таймер APIC на периодические прерывания вектора
   LAPIC_TIMER_VECTOR с частотой freq_hz. Требует предварительной
   калибровки (lapic_timer_calibrate(), см. ниже) -- частота тактов
   локального таймера НЕ документирована архитектурно и отличается от
   машины к машине (обычно это частота шины/некоторая её производная),
   в отличие от PIT (см. include/timer.h), чья частота входа известна
   заранее (PIT_BASE_FREQ). */
void lapic_timer_start_periodic(u32 freq_hz);

/* Калибрует частоту тактов локального таймера ОТНОСИТЕЛЬНО уже
   работающего PIT (см. include/timer.h) -- запускает таймер APIC в
   режиме one-shot с заведомо большим начальным значением, ждёт
   известный интервал по PIT, смотрит, сколько тактов APIC успело
   пройти, и вычисляет тактов-в-секунду. Вызывается ОДИН раз на BSP (см.
   smp_init() в kernel/smp.c) -- результат одинаков для всех ядер одного
   и того же процессора (однородная SMP-система, что справедливо для
   QEMU и подавляющего большинства реальных многоядерных x86_64), так
   что каждый AP просто переиспользует уже посчитанное значение,
   вызывая lapic_timer_start_periodic() напрямую. */
void lapic_timer_calibrate(void);

#endif
