#ifndef USB_HID_H
#define USB_HID_H

#include "types.h"
#include "usb.h"

/* usb_hid.h -- драйвер USB HID-устройств, ограниченный Boot Protocol
 * (USB HID 1.11, приложение B) -- то есть ровно тем подмножеством,
 * которое обязана понимать любая клавиатура/мышь ради совместимости с
 * BIOS. Полный Report Protocol (произвольные HID report descriptor'ы)
 * не разбирается -- boot-протокол даёт фиксированный, всегда известный
 * формат отчёта (8 байт для клавиатуры, 3-4 байта для мыши), чего с
 * лихвой хватает шеллу этого ядра.
 *
 * Клавиатура интегрируется в drivers/keyboard.c: символы, набранные на
 * USB-клавиатуре, попадают в тот же поток, что и с PS/2 -- шелл и
 * остальной код не отличают одно от другого (см. usb_hid_kbd_haskey()/
 * usb_hid_kbd_getchar() ниже и их использование в keyboard.c).
 *
 * Мышь пока не имеет потребителя в остальной части ядра (у
 * MeetlookCoreOS нет GUI) -- но эндпоинт опрашивается и состояние
 * (кнопки, накопленное смещение) доступно через usb_mouse_get_state(),
 * которое использует команда шелла 'mouse' просто чтобы показать, что
 * устройство живо.
 *
 * И клавиатура, и мышь опрашиваются в отдельной фоновой задаче
 * планировщика (см. usb_hid_start_polling()), а не в горячем цикле
 * keyboard_getchar() -- так операции чтения USB-репорта (которые могут
 * не завершиться мгновенно, если устройство ещё не готово ответить)
 * никогда не тормозят ввод с PS/2. */

/* Вызывается из usb.c для каждого найденного устройства с
   if_class == USB_CLASS_HID. Проверяет, что это boot-protocol
   клавиатура или мышь (по if_subclass/if_protocol) и что у неё есть
   interrupt IN точка; если да -- переводит устройство в Boot Protocol
   и регистрирует его для фонового опроса. Иначе тихо игнорирует
   устройство (обычный HID без boot-протокола, например джойстик, этим
   драйвером не поддерживается). */
void usb_hid_probe(usb_device_t *dev);

/* Создаёт фоновую задачу опроса (task_create), если хотя бы одна
   клавиатура или мышь были зарегистрированы через usb_hid_probe().
   Вызывается один раз из usb_init() после перебора всех портов. */
void usb_hid_start_polling(void);

/* ---- Клавиатура: используется drivers/keyboard.c ---- */
bool_t usb_hid_kbd_haskey(void);
char   usb_hid_kbd_getchar(void); /* не блокирует -- вызывать только если haskey() истинно */

/* ---- Мышь: используется командой 'mouse' в shell.c ---- */
bool_t usb_hid_mouse_present(void);
void   usb_hid_mouse_get_state(u8 *buttons, s32 *x, s32 *y);

#endif
