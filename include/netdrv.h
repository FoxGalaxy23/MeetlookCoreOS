#ifndef NETDRV_H
#define NETDRV_H

#include "types.h"
#include "net.h"

/* netdrv.h -- Фаза 4, подшаг 4 (см. CONTAINER_ARCHITECTURE.md): последний
 * шаг выноса сетевой карты из ядра в контейнер. То, чем раньше был
 * целиком drivers/rtl8139.c (сброс, кольцо приёма, буферы передачи,
 * обработчик IRQ), теперь -- apps/rtl8139d.c, обычный ring-3 контейнер
 * поверх уже готовых CAP_IO (подшаг 1) + CAP_IRQ (подшаг 2) +
 * CAP_NET_BRIDGE (подшаг 3). Здесь, в kernel/netdrv.c, остаётся ровно
 * тот минимум, который принципиально НЕ может быть сделан из ring 3:
 *
 *   1. Перебор шины PCI и запись в её конфигурационное пространство
 *      (порты 0xCF8/0xCFC, drivers/pci.c) -- общий ресурс, разделяемый
 *      между ВСЕМИ устройствами машины, а не диапазон портов одной
 *      конкретной карты. CAP_IO манифеста -- это диапазон портов ОДНОГО
 *      устройства; дать контейнеру доступ к 0xCF8/0xCFC означало бы дать
 *      ему доступ к конфигурации ЛЮБОГО PCI-устройства в системе, ровно
 *      то, от чего манифест обязан защищать. Поэтому обнаружение карты,
 *      включение bus mastering и мягкий сброс остаются здесь -- это и
 *      есть тот самый "драйвер шины", который по духу Windows 10X
 *      (см. верх CONTAINER_ARCHITECTURE.md) должен оставаться в Core OS.
 *
 *   2. Физические адреса DMA-буферов кольца приёма/передачи. RBSTART и
 *      TSAD0..3 -- ФИЗИЧЕСКИЕ адреса, а адресное пространство ring-3
 *      процесса, в отличие от самого ядра, НЕ identity-mapped (см.
 *      общий комментарий у mmio_read32(), include/io.h) -- обычный
 *      процесс в принципе не может узнать физический адрес собственной
 *      памяти. Решение -- переиспользовать уже существующий CAP_SHM
 *      (include/ipc.h, тот же примитив, которым пользуется
 *      apps/ipctest.c): здесь DMA-буферы выделяются ЗАВЕДОМО ПОДРЯД
 *      идущими физическими кадрами (pmm_alloc_frames(), не
 *      pmm_alloc_frame() по одному -- иначе кольцо приёма было бы
 *      физически рвано, а карта об этом ничего не знает и просто пишет
 *      подряд) и регистрируются как ИМЕНОВАННЫЕ shm-сегменты
 *      ("netdrv-rx"/"netdrv-tx", shm_create_from_frames(), kernel/ipc.c).
 *      Контейнер-драйвер затем находит их тем же SYS_SHM_CREATE(name,
 *      ...)/SYS_SHM_ATTACH(), которым уже пользуется apps/ipctest.c --
 *      получая обычный пользовательский указатель, указывающий на ТЕ ЖЕ
 *      физические страницы, куда карта пишет и откуда читает по DMA.
 *
 *   3. Собственно запись физических адресов этих буферов в RBSTART/
 *      TSAD0..3 -- по той же причине (только ядро знает физический
 *      адрес), делается здесь один раз, ДО того, как контейнер вообще
 *      запущен. IMR/RCR/TCR/CMD, наоборот, здесь НЕ трогаются --
 *      остаются нулевыми (см. netdrv_probe() ниже) -- их включает уже
 *      сам контейнер (apps/rtl8139d.c), когда он готов обслуживать и
 *      IRQ, и netbridge; если бы карта могла начать слать прерывания
 *      или принимать пакеты раньше, чем контейнер стартовал, эти
 *      события были бы просто потеряны (некому их забрать).
 *
 * Всё остальное, что раньше было в drivers/rtl8139.c -- IMR/RCR/TCR,
 * разбор кольца приёма (включая перенос кадра через границу буфера),
 * TSD/TOK при передаче, сам обработчик IRQ -- теперь целиком в
 * apps/rtl8139d.c, обычном ring-3 коде поверх CAP_IO/CAP_IRQ/
 * CAP_NET_BRIDGE/CAP_SHM.
 *
 * ---- Как контейнер узнаёт io_base/irq_line ----
 *
 * Оба значения известны только В МОМЕНТ обнаружения карты: PCI BAR0 --
 * не константа, а то, куда её поставил BIOS/SeaBIOS при ЭТОЙ конкретной
 * загрузке; IRQ -- из конфигурационного пространства той же карты.
 * Обычный манифест на диске (в отличие от, скажем,
 * rootfs/containers/iodemo-cmos.manifest, где io_base известен заранее
 * и захардкожен -- порты CMOS фиксированы архитектурой) не может знать
 * их заранее. Вместо этого netdrv_launch() ниже строит
 * container_manifest_t прямо в памяти (тот же приём, что описан как
 * пример в CONTAINER_ARCHITECTURE.md, Фаза 1) и передаёт оба значения
 * через argv[1]/argv[2] (десятичные строки) -- ровно то же самое можно
 * было бы сделать вручную из шелла: 'runc /containers/rtl8139d.manifest
 * <io_base> <irq>' (см. rootfs/containers/rtl8139d.manifest за тем,
 * когда это может понадобиться и почему сам файл не содержит верных
 * io_base/irq для произвольной машины). */

/* Обнаруживает RTL8139 на шине PCI, включает bus mastering, делает
   мягкий сброс, читает "прошитый" MAC-адрес и выделяет + программирует
   DMA-буферы приёма/передачи (RBSTART/TSAD0..3) -- см. общий комментарий
   выше за тем, почему именно это остаётся в ядре. НЕ включает
   приём/передачу (IMR/RCR/TCR/CMD остаются нулевыми) и НЕ запускает
   контейнер -- см. netdrv_launch() ниже, вызываемый отдельно, уже после
   vfs_init() (контейнеру нужна файловая система, см. kernel/container.c:
   container_spawn() -> fs_get_app()/fs_read_file()). Возвращает FALSE,
   если карта физически не найдена (тогда net_is_up() должен остаться
   FALSE, как и раньше) -- *out_mac в этом случае не трогается. Вызывать
   РОВНО ОДИН РАЗ, из net_init() (net/net.c), ровно там же, где раньше
   вызывался rtl8139_init(). */
bool_t netdrv_probe(mac_addr_t *out_mac);

/* Запускает apps/rtl8139d.c как контейнер-драйвер в ОТДЕЛЬНОМ потоке
   ядра (task_create(), не блокирует вызывающего -- container_spawn()
   внутри блокируется до завершения контейнера, а он не должен завершаться
   в норме никогда, см. netdrv_launch_task(), kernel/netdrv.c). Ничего не
   делает, если netdrv_probe() не нашёл карту либо ещё не вызывался.
   Требует, чтобы VFS уже была смонтирована -- вызывать из kernel/kernel.c
   строго после vfs_init(). */
void netdrv_launch(void);

#endif
