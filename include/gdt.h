#ifndef GDT_H
#define GDT_H

#include "types.h"

/* gdt.h -- глобальная таблица дескрипторов + TSS.
 *
 * До этого файла в системе была только временная GDT из boot/boot.s:
 * два дескриптора (код/данные кольца 0), без TSS и без чего-либо для
 * ring 3. Этого хватало, пока всё (и ядро, и "пользовательские"
 * бинарники из loader.c) исполнялось в кольце 0 -- но именно поэтому
 * любая программа могла выполнить cli, залезть в порты или прочитать
 * произвольную физическую память одной инструкцией.
 *
 * gdt_init() строит полноценную GDT (кольцо 0 + кольцо 3, код и данные
 * отдельно, как того требует long mode) и TSS, нужный ровно для одной
 * вещи: чтобы процессор знал, на какой стек переключиться сам, когда
 * прерывание или исключение застаёт программу в ring 3 (переход
 * CPL 3 -> 0, см. Intel SDM Vol.3 §7.2.1 / AMD64 APM Vol.2 §12.2.5).
 * Без TSS.RSP0 такой переход попросту не определён и переход в ring 3
 * гарантированно уронит систему на первом же прерывании (таймер,
 * клавиатура, что угодно).
 *
 * Селекторы ниже жёстко привязаны к раскладке таблицы в gdt.c -- если
 * поменяете порядок записей там, поменяйте и константы здесь. */

#define GDT_KERNEL_CODE_SEL 0x08u
#define GDT_KERNEL_DATA_SEL 0x10u
#define GDT_USER_CODE_SEL   0x1Bu   /* индекс 3, RPL=3 (0x18 | 3) */
#define GDT_USER_DATA_SEL   0x23u   /* индекс 4, RPL=3 (0x20 | 3) */
#define GDT_TSS_SEL         0x28u   /* индекс 5 (системный дескриптор занимает слоты 5 и 6) */

/* Строит GDT+TSS, загружает их (lgdt/ltr) и перезагружает сегментные
   регистры (включая CS через дальний переход). Должна быть вызвана
   один раз при старте ЯДРА, до включения прерываний -- см. kernel.c.
   После этого вызова прежняя временная GDT из boot.s больше не
   используется (память под неё не освобождаем, она статическая).
   Строит GDT+TSS ИМЕННО для BSP (this_cpu()->cpu_index == 0, см.
   include/percpu.h -- percpu_init_early(0, ...) должен быть вызван
   раньше этой функции). Для каждого AP используется gdt_init_ap() ниже. */
void gdt_init(void);

/* SMP: то же самое, что gdt_init(), но для ядра this_cpu()->cpu_index != 0
   (см. include/percpu.h) -- строит СОБСТВЕННЫЙ GDT+TSS этого AP (см.
   общий комментарий в kernel/gdt.c про то, почему TSS обязан быть
   персональным для каждого физического ядра) и загружает их (lgdt/ltr)
   НА ЭТОМ ядре. Вызывается один раз из ap_entry64() (kernel/smp.c),
   сразу после percpu_init_early() для этого AP. */
void gdt_init_ap(void);

/* Обновляет TSS.RSP0 -- адрес вершины стека, на который процессор сам
   переключится при следующем прерывании/исключении, случившемся в
   ring 3. Вызывается из планировщика (kernel/task.c: schedule()) перед
   каждым переключением на процессную задачу (см. include/task.h) --
   значение обязано быть валидным адресом в пределах СОБСТВЕННОГО
   стека ядра именно этой задачи, не используемого в этот момент никем
   ещё -- иначе первое же прерывание в ring 3 уронит систему в double
   fault. Трогает TSS ТОЛЬКО ТОГО ядра, на котором вызвана (см.
   this_cpu() в include/percpu.h) -- на SMP каждое ядро обязано иметь
   собственный TSS.RSP0 (см. общий комментарий в kernel/gdt.c), иначе два
   ядра, оба обслуживающие ring3-прерывания примерно одновременно,
   затирали бы RSP0 друг друга. */
void gdt_set_kernel_stack(u64 rsp0);

/* Программирует битовую карту портов ввода-вывода ТЕКУЩЕГО физического
   ядра (this_cpu(), как и gdt_set_kernel_stack() выше) так, чтобы из
   ring 3 были разрешены (и ТОЛЬКО они) порты [io_base, io_base+io_len).
   io_len == 0 -- явный и самый частый случай: снять вообще все
   разрешения (задача без CAP_IO, см. include/container.h). Как и
   gdt_set_kernel_stack(), вызывается планировщиком (kernel/task.c:
   schedule()) перед переключением на задачу с собственным адресным
   пространством -- ДО этого момента карта этого CPU всё ещё хранит
   диапазон ПРЕДЫДУЩЕЙ выполнявшейся на нём задачи, так что пропуск
   вызова означал бы утечку чужого доступа к портам. */
void gdt_apply_io_permissions(u16 io_base, u16 io_len);

#endif
