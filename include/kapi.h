#ifndef KAPI_H
#define KAPI_H

/* kapi.h -- таблица функций ядра, которую ядро передаёт пользовательскому
 * бинарнику при запуске (см. loader.h / kernel/loader.c).
 *
 * ВАЖНО про модель выполнения: у MeetlookCoreOS нет ни колец защиты
 * (используется единственный плоский набор GDT-дескрипторов без ring 3),
 * ни отдельных адресных пространств (paging делает identity-map первого
 * 1 GiB и используется только для перехода в long mode). Это значит, что
 * пользовательский бинарник исполняется совершенно на тех же правах,
 * что и само ядро (ring 0, полный доступ к портам ввода-вывода и ко всей
 * физической памяти). Именно это и требуется, чтобы такой бинарник мог
 * быть полноценным системным сервисом: графическим сервером, драйвером
 * диска, планировщиком и т.д., а не "приложением" в привычном смысле.
 *
 * kapi_t -- это не механизм защиты, а просто удобный ABI: бинарник
 * собирается и линкуется отдельно от ядра (свой линковочный скрипт,
 * фиксированный адрес загрузки), поэтому он не может напрямую вызывать
 * функции ядра по имени -- вместо этого loader передаёт ему указатель на
 * структуру с адресами нужных функций.
 *
 * Бинарник, разумеется, не обязан пользоваться kapi -- поскольку он
 * выполняется в кольце 0, он может напрямую использовать in/out,
 * читать/писать любую физическую память, вешать свои обработчики и т.п.
 * kapi лишь избавляет от необходимости дублировать код, который уже
 * есть в ядре (вывод текста, работа с ФС, чтение RTC...).
 */

#include "types.h"
#include "ramfs.h"
#include "rtc.h"
#include "storage.h"

/* Версия 2: ata_* (только IDE) заменены на storage_* (общий интерфейс
   IDE + SATA, см. storage.h) -- у бинарника, собранного под версию 1,
   изменился бы состав и порядок полей после fs_current_drive, поэтому
   версия увеличена. Бинарники всегда собираются вместе с ядром из
   исходников (см. Makefile: rootfs зависит от apps), так что это не
   проблема для этого проекта, но именно для таких случаев здесь есть
   abi_version.
   Версия 3: добавлена поддержка UFS (см. fs/ufs.c, include/ufs.h) --
   у kapi_t появилось новое поле fs_backend_is_ufs сразу после
   fs_backend_is_fat32.
   Версия 4: добавлен менеджер физической памяти (kernel/pmm.c) и куча
   ядра (kernel/kheap.c) -- у kapi_t появился блок kmalloc/kfree/...
   и функции статистики памяти сразу после power_reboot. До этой
   версии у бинарников не было вообще никакого способа динамически
   выделять память -- только статический буфер загрузки/собственный
   .bss, поэтому это не косметическое расширение ABI. */
#define MLKAPI_VERSION 4u

typedef struct kapi {
    u32 abi_version;   /* бинарник должен сверить с MLKAPI_VERSION */

    /* ---- консоль / текстовый вывод ---- */
    void (*kprintf)(const char *fmt, ...);
    u32  (*console_readline)(char *buf, u32 maxlen);

    /* ---- VGA текстовый режим (0xB8000) ----
       Этого достаточно, чтобы написать собственный консольный/графический
       сервер, полностью управляющий экраном, поверх текстового режима. */
    void (*vga_init)(void);
    void (*vga_clear)(void);
    void (*vga_putc)(char c);
    void (*vga_puts)(const char *s);
    void (*vga_set_color)(u8 fg, u8 bg);
    void (*vga_backspace)(void);
    void (*vga_update_cursor)(void);
    void (*vga_scroll_if_needed)(void);

    /* ---- клавиатура ---- */
    char   (*keyboard_getchar)(void);   /* блокирующее чтение (poll) */
    bool_t (*keyboard_haskey)(void);    /* неблокирующая проверка */

    /* ---- прямой доступ к портам ввода-вывода ----
       Не привилегированная операция для бинарника (он и так в ring 0),
       просто общий интерфейс вместо дублирования asm в каждом бинарнике. */
    void (*outb)(u16 port, u8 val);
    u8   (*inb)(u16 port);
    void (*outw)(u16 port, u16 val);
    u16  (*inw)(u16 port);
    void (*insw)(u16 port, void *addr, u32 count);
    void (*outsw)(u16 port, const void *addr, u32 count);
    void (*io_wait)(void);

    /* ---- виртуальная файловая система (RAMFS, FAT32 или UFS) ---- */
    void   (*fs_ls)(void);
    bool_t (*fs_cd)(const char *name);
    bool_t (*fs_mkdir)(const char *name);
    bool_t (*fs_rm)(const char *name);
    bool_t (*fs_write_file)(const char *name, const char *data, u32 len);
    bool_t (*fs_cat)(const char *name);
    void   (*fs_pwd)(char *buf, u32 bufsize);
    bool_t (*fs_read_file)(const char *name, void *buf, u32 bufsize, u32 *out_size);
    ramfs_app_id_t (*fs_get_app)(const char *name);
    bool_t (*fs_backend_is_fat32)(void);
    bool_t (*fs_backend_is_ufs)(void);
    u32    (*fs_current_drive)(void);

    /* ---- прямой доступ к дискам ----
       Экспонируется, чтобы можно было написать альтернативный драйвер
       файловой системы как отдельный бинарник, не трогая ядро. Работает
       одинаково для дисков и на IDE, и на SATA (AHCI) -- storage_dev_t
       не раскрывает, через какую шину подключён конкретный диск. */
    u32              (*storage_drive_count)(void);
    storage_dev_t   *(*storage_get_drive)(u32 index);
    bool_t           (*storage_read_sectors)(u32 drive_index, u32 lba, u8 count, void *buf);
    bool_t           (*storage_write_sectors)(u32 drive_index, u32 lba, u8 count, const void *buf);

    /* ---- время и питание ---- */
    void (*rtc_read)(rtc_time_t *t);
    void (*power_shutdown)(void);
    void (*power_reboot)(void);

    /* ---- динамическая память ----
       Общая куча ядра (kernel/kheap.c) для всех бинарников: своей
       собственной кучи у каждого бинарника нет (нет отдельных адресных
       пространств), поэтому это одна общая куча на всю систему, как и
       положено при общем плоском адресном пространстве. Бинарник обязан
       вызывать kfree для всего, что выделил через kmalloc/kcalloc --
       ядро не отслеживает, кому какой блок принадлежит, и не освобождает
       память автоматически после завершения бинарника. */
    void  *(*kmalloc)(u32 size);
    void  *(*kcalloc)(u32 nmemb, u32 size);
    void  *(*krealloc)(void *ptr, u32 new_size);
    void   (*kfree)(void *ptr);

    /* ---- статистика памяти (для команд вроде meminfo) ---- */
    u32 (*mem_total_bytes)(void);      /* вся физическая память, обнаруженная при загрузке */
    u32 (*mem_free_bytes)(void);       /* физическая память, ещё не выданная PMM никому */
    u32 (*heap_total_bytes)(void);     /* размер кучи ядра целиком */
    u32 (*heap_used_bytes)(void);      /* сколько из кучи ядра сейчас занято */

    /* ---- запуск другого бинарника изнутри бинарника ---- */
    s32 (*run_file)(const char *path, u32 argc, char **argv);

    /* ---- регистрация "тикового" обработчика ----
       У системы нет прерываний таймера и планировщика (один поток
       управления), поэтому это кооперативный, а не преэмптивный
       механизм: shell вызывает все зарегистрированные обработчики перед
       каждым выводом приглашения. Этого достаточно, чтобы, например,
       фоновый сервис (графический сервер, монитор и т.п.) периодически
       получал управление, не будучи вызванным явно командой из shell.
       Возвращает FALSE, если таблица обработчиков уже заполнена. */
    bool_t (*register_tick)(void (*fn)(void));
} kapi_t;

/* Точка входа пользовательского бинарника. Компилируется и линкуется
   отдельно от ядра (см. apps/user.ld, include/mlapp.h) и загружается по
   фиксированному адресу загрузчиком (kernel/loader.c), который вызывает
   её как обычную функцию Си -- никакого перехода между кольцами не
   происходит, т.к. кольцо одно и то же. */
typedef s32 (*app_main_t)(const kapi_t *kapi, u32 argc, char **argv);

#endif
