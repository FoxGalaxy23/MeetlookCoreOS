#ifndef LOADER_H
#define LOADER_H

#include "types.h"
#include "paging.h"

/* loader.c -- загрузчик пользовательских бинарников.
 *
 * Формат: настоящий статический ELF64 (ET_EXEC, БЕЗ PT_INTERP -- сборка
 * с -static, никакого динамического линковщика в системе нет) со
 * стандартными PT_LOAD-сегментами, собираемый apps/user.ld. Все
 * PT_LOAD-сегменты обязаны укладываться в фиксированное окно
 * [PROC_CODE_BASE, PROC_CODE_BASE + PROC_CODE_SIZE) = [APP_LOAD_ADDR,
 * APP_LOAD_ADDR + APP_MAX_SIZE) (см. include/memlayout.h) -- elf_load()
 * это проверяет и отклоняет всё, что выходит за пределы, ДО того, как
 * успеет что-то отобразить. Загрузчик:
 *   1. проверяет, что файл в текущей ФС помечен как исполняемый
 *      (RAMFS_APP_BINARY, см. fs_get_app());
 *   2. парсит ELF-заголовок и program headers (elf_load(), см. ниже);
 *   3. для sandboxed-режима создаёт СОБСТВЕННОЕ адресное пространство
 *      процесса (address_space_t, см. include/paging.h,
 *      kernel/process.c) и мапит туда каждый PT_LOAD-сегмент отдельными
 *      физическими кадрами (as_alloc_and_map()), копируя файловую часть
 *      и обнуляя "хвост" (.bss) -- у каждого процесса СВОИ физические
 *      страницы под одними и теми же виртуальными адресами, поэтому
 *      несколько разных бинарников прекрасно уживаются одновременно
 *      (см. ниже); для god-режима -- копирует сегменты прямо по
 *      физическим адресам, как раньше;
 *   4. запускает точку входа: в sandboxed-режиме -- в ring 3 через
 *      process_run_sandboxed()/process_execve() (kernel/process.c), в
 *      god-режиме -- прямым Си-вызовом с сигнатурой app_main_t
 *      (см. kapi.h), передавая ей таблицу kapi и argv.
 *
 * Есть два режима запуска (см. функции ниже):
 *   - loader_run_file_sandboxed() -- по умолчанию, ring 3: у КАЖДОГО
 *     процесса СВОЁ адресное пространство (в отличие от исторической
 *     версии, где память была общей на всю систему) -- см. process.c и
 *     kernel/paging.c за подробностями (per-process PD0, COW при
 *     fork()). Плюс к изоляции по памяти есть и обычная аппаратная
 *     граница доступа (GDT/TSS/биты U/S в таблицах страниц, см.
 *     include/gdt.h, include/paging.h): программе позволено читать и
 *     писать только собственные код/данные/bss/кучу/стек, а нужный ей
 *     сервис от ядра (печать, чтение клавиатуры, fork/execve и т.п.)
 *     она получает только через системные вызовы (int 0x80, см.
 *     include/sysabi.h). Она завершается через SYS_EXIT (см.
 *     include/usyscall.h), а не через return -- хотя снаружи (для
 *     shell) это выглядит как обычное возвращаемое из функции значение.
 *   - loader_run_file_god() -- старый режим, ring 0, полный доступ к
 *     памяти/портам ровно как у ядра, argv/return как обычный вызов
 *     функции с сигнатурой app_main_t (kapi.h). Доступен только через
 *     команду шелла 'rungod' и только root (см. shell/shell.c).
 *
 * Про "один процесс за раз": process_run_sandboxed() (запускается
 * командой шелла 'run') синхронно ждёт завершения ИМЕННО того процесса,
 * который она сама запустила (как обычный вызов функции с точки зрения
 * shell) -- но это ограничение самого шелла как вызывающего кода, а не
 * архитектурное ограничение ядра: пока шелл ждёт, планировщик (см.
 * kernel/task.c) как обычно крутит round-robin между ним и ЛЮБЫМИ
 * другими одновременно живыми задачами -- в т.ч. потомками fork()
 * запущенного процесса, или другими процессами/потоками-сервисами,
 * зарегистрированными ранее. Размер одного образа (код+данные+bss)
 * по-прежнему ограничен APP_MAX_SIZE -- ЭТО ограничение на размер
 * отдельного бинарника, а не на число одновременно загруженных. */

#define APP_LOAD_ADDR ((void *)0x02000000ull) /* == PROC_CODE_BASE, include/memlayout.h --
    поднято в Фазе 4.4 вместе со всем окном процесса, см. подробный
    разбор там же и в kernel/kheap.c (стек BSP из boot.s заходил в
    старое окно [6 MiB,...), из-за чего первый же 'run'/'runc' после
    входа в shell валил систему -- см. CONTAINER_ARCHITECTURE.md). */
#define APP_MAX_SIZE  ((u32)0x00200000u)   /* 2 MiB */

/* Загружает и запускает файл name (путь или имя относительно текущего
   каталога активной ФС) в песочнице ring 3 (см. include/usermode.h,
   include/sysabi.h). Программа получает доступ ТОЛЬКО к собственной
   памяти (код/данные/bss + отдельный стек) и обязана пользоваться
   системными вызовами для всего остального -- попытка выйти за эти
   рамки убивает только её саму (см. kernel/isr.c), а не всю систему.
   kapi_t она не получает (первым аргументом app_main всегда придёт
   NULL) -- функции ядра из ring 3 напрямую не видны. Именно сюда идёт
   обычная команда шелла 'run'. Возвращает код возврата бинарника, либо
   -1, если файл не найден / не является исполняемым бинарником /
   слишком велик. */
s32 loader_run_file_sandboxed(const char *name, u32 argc, char **argv);

/* Старый режим: бинарник выполняется как раньше -- в кольце 0, с
   полной таблицей kapi_t и теми же правами, что и само ядро (см.
   include/kapi.h). Фаза 5, подшаг 5.5 (см. CONTAINER_ARCHITECTURE.md):
   команда 'rungod', которая раньше была единственным путём сюда из
   интерактивного шелла (root only), сознательно НЕ перенесена в новый
   apps/shell.c -- шелл сам стал обычным ring-3 контейнером и физически
   не может выдать ring-0 доступ никому, не разрушив всю модель
   capability (см. общий комментарий в начале apps/shell.c). Функция
   остаётся -- её по прежнему зовёт kapi_t.run_file (kernel/loader.c)
   для системного кода, у которого УЖЕ есть kapi_t (например, если
   ring-0 сервис сам захочет породить другой ring-0 сервис) -- просто
   сегодня в дереве нет ни одного вызывающего, который дошёл бы до неё
   этим путём (ни один процесс в системе больше не запускается в
   ring 0). */
s32 loader_run_file_god(const char *name, u32 argc, char **argv);

/* Вызывается из отдельного потока ядра (kernel/kernel.c, задача
   "tick-services", заведена в kernel_main()) каждые ~10 мс, чтобы дать
   загруженным ранее бинарникам-сервисам шанс на выполнение. До Фазы 5,
   подшага 5.5 вызывалась прямо из цикла shell_run() (shell/shell.c) --
   когда шелл был кодом ядра, это было естественно; теперь, когда он
   обычный ring-3 контейнер без доступа к функциям ядра (apps/shell.c),
   этот крючок дёргает кто-то другой, иначе он просто перестал бы
   работать. */
void loader_run_tick_services(void);

/* Парсит и загружает статический ELF64 в указанное адресное пространство as.
   Если as == NULL, загружает непосредственно по физическим адресам (god mode).
   Возвращает виртуальный адрес точки входа или 0 при ошибке. */
u64 elf_load(const void *elf_data, u32 elf_size, address_space_t *as);

#endif
