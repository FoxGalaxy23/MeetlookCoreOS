#ifndef IRQBRIDGE_H
#define IRQBRIDGE_H

#include "types.h"

/* irqbridge.h -- мост между аппаратным IRQ (обработчик в ring 0,
 * контекст прерывания) и ожидающей его user-space задачей. Фаза 4,
 * подшаг 2 (см. CONTAINER_ARCHITECTURE.md); строится на CAP_IO из
 * подшага 1 -- контейнер, которому нужно ждать конкретную линию IRQ,
 * почти всегда ей же и читает регистры устройства через CAP_IO, просто
 * САМ доступ к портам уже не нуждается в syscall'е (см.
 * include/container.h), а вот "проснуться, когда придёт прерывание"
 * нуждается -- отсюда SYS_IRQ_WAIT (include/sysabi.h).
 *
 * Механизм -- по одному semaphore_t (include/sync.h) на каждую из 16
 * legacy IRQ-линий: обработчик, общий для ЛЮБОЙ переданной мосту линии
 * (irq_bridge_dispatch(), kernel/irqbridge.c), делает sem_post() по
 * номеру линии, вычисленному прямо из regs->int_no; sys_irq_wait()
 * (kernel/syscall.c) делает sem_wait() на той же линии. semaphore_t уже
 * сам по себе безопасен для вызова из настоящего контекста прерывания
 * (см. общий комментарий в kernel/sync.c -- sem_post()/sem_wait() сами
 * оборачивают свою критическую секцию в cli/sti, а не только в
 * spin_lock) -- отдельной синхронизации здесь придумывать не пришлось.
 *
 * Капабилити (CAP_IRQ, include/container.h) и то, какой именно номер
 * линии разрешён КОНКРЕТНОЙ задаче -- забота syscall.c/container.c, не
 * этого файла: irqbridge_wait() ничего не знает про манифесты и
 * доверяет вызывающему, что тот уже всё проверил. Разделение
 * ответственности то же самое, что и у CAP_IO: "проверка прав" отдельно
 * от "механизм". */

/* Вызывается один раз при старте ядра (kernel/kernel.c), после
   isr_init() и до pic_remap()/sti -- инициализирует все 16 семафоров
   нулевым счётчиком. */
void irqbridge_init(void);

/* Гарантирует, что для линии irq (0-15) установлен мост (идемпотентно:
   повторные вызовы для уже установленной линии ничего не переустанавливают),
   затем БЛОКИРУЕТ вызывающего до следующего срабатывания этой линии.
   Возвращает FALSE, не блокируя, если:
     - irq >= 16 (неверный номер линии);
     - линия уже занята ДРУГИМ обработчиком ядра, не этим мостом (см.
       irq_handler_is_registered(), include/isr.h) -- то есть кто-то
       (таймер, сетевой драйвер) уже владеет этой линией напрямую, и
       мост не имеет права её перехватывать.
   При первом успешном вызове для данной линии дополнительно снимает с
   неё маску PIC (pic_clear_mask(), include/pic.h) -- до этого момента
   линия физически не может генерировать прерывания вообще (все линии
   замаскированы по умолчанию, см. pic_remap(), kernel/pic.c). */
bool_t irqbridge_wait(u8 irq);

#endif
