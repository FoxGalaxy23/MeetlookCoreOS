; context.s -- сердце переключения задач: context_switch и точка входа
; новой задачи (task_trampoline). См. include/context.h за объяснением
; общей идеи и kernel/task.c за тем, как строится начальный стек новой
; задачи (там же документирован точный порядок полей, который здесь
; предполагается).
;
; Сознательно НЕ используется iretq/интерфейс "как в прерывании": вместо
; этого context_switch -- обычная функция по System V AMD64 ABI, которая
; сохраняет ровно то, что обязана сохранять любая функция (callee-saved
; регистры: rbp, rbx, r12-r15), после чего просто переключает rsp на
; чужой стек и "ret". Всё, что нужно восстановить сверх этого (rip,
; регистры общего назначения, флаги) -- либо восстановится автоматически
; самим механизмом ret/дальнейшего разворачивания стека вызовов (для
; задачи, которую до этого вытеснили посреди работы), либо не имело
; смысла сохранять (для только что созданной задачи, см. task_trampoline).

global context_switch
global task_trampoline
extern task_entry_wrapper

; void context_switch(u64 *old_rsp, u64 new_rsp)
;   rdi = адрес, куда сохранить текущий rsp (обычно &prev_task->rsp)
;   rsi = новое значение rsp (обычно next_task->rsp)
context_switch:
    push rbp
    push rbx
    push r12
    push r13
    push r14
    push r15

    mov [rdi], rsp     ; сохраняем контекст ПРЕЖНЕЙ задачи
    mov rsp, rsi        ; переключаемся на стек НОВОЙ задачи

    pop r15
    pop r14
    pop r13
    pop r12
    pop rbx
    pop rbp
    ret                 ; "возврат" в новую задачу -- либо в её прошлый
                        ; вызов context_switch (обычное вытеснение), либо
                        ; в task_trampoline ниже (задача запускается впервые)

; Точка первого входа только что созданной задачи. task_create() (см.
; kernel/task.c) заранее кладёт на стек новой задачи такие значения
; r12/r13, что после pop'ов выше в реальных регистрах CPU оказывается:
;   r12 = указатель на entry-функцию задачи (task_entry_t)
;   r13 = аргумент, который нужно ей передать (void *arg)
; Дальше это просто обычный вызов C-функции по ABI (rdi = 1-й аргумент,
; rsi = 2-й), которая вызовет entry(arg) и корректно завершит задачу,
; если entry когда-нибудь вернётся (см. task_entry_wrapper в task.c).
task_trampoline:
    mov rdi, r13        ; 1-й аргумент task_entry_wrapper: void *arg
    mov rsi, r12        ; 2-й аргумент: task_entry_t entry
    call task_entry_wrapper
    ; Сюда мы никогда не должны попасть: task_entry_wrapper сама
    ; вызывает task_exit(), который не возвращается. Останавливаемся
    ; на всякий случай, а не проваливаемся в случайный код дальше.
.unreachable:
    cli
    hlt
    jmp .unreachable
