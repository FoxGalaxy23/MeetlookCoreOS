/* irqbridge.c -- см. include/irqbridge.h за общей идеей. */

#include "irqbridge.h"
#include "isr.h"
#include "pic.h"
#include "sync.h"

static semaphore_t g_irq_sem[16];
static bool_t g_bridge_owns[16]; /* TRUE -- эту линию когда-либо успешно застолбил irqbridge_wait() */

void irqbridge_init(void) {
    for (u32 i = 0; i < 16; i++) {
        sem_init(&g_irq_sem[i], 0);
        g_bridge_owns[i] = FALSE;
    }
}

/* Общий обработчик ЛЮБОЙ линии, которую застолбил мост -- в отличие от
   выделенных обработчиков ядерных драйверов (timer_irq_handler,
   kernel/timer.c -- после Фазы 4.4 это единственный оставшийся пример:
   у сетевой карты такого обработчика в ядре больше нет вообще, см.
   include/netdrv.h), одна и та же функция
   регистрируется на РАЗНЫЕ линии: номер линии не захвачен в замыкании
   (в C такого и не бывает), а вычисляется прямо из regs->int_no --
   irq_handler() (kernel/isr.c) вызывает нас уже после того, как сам
   определил номер и отправил EOI, но нам он его не передаёт напрямую
   (сигнатура isr_handler_t одна на всех), так что вычисляем заново тем
   же способом.
 *
 * КРИТИЧНО (баг, найденный и исправленный при разборе Фазы 4.4 --
 * "DHCP-запрос уходит на провод... но RX-роль его не подхватывает",
 * см. CONTAINER_ARCHITECTURE.md): irq_handler() (kernel/isr.c) шлёт EOI
 * ДО вызова этой функции, а сама эта функция лишь будит ожидающую
 * задачу (sem_post) -- НАСТОЯЩЕЕ подтверждение устройству (запись в его
 * собственный ISR-регистр, например outw(io_base+REG_ISR,status) в
 * apps/rtl8139d.c) происходит СИЛЬНО ПОЗЖЕ, уже в ring 3, когда
 * разбуженная задача до него дойдёт. Для LEVEL-triggered устройства
 * (обычный PCI, как RTL8139) это означает: линия физически остаётся
 * поднятой всё это время. Раз EOI на 8259 уже отправлен, а линия
 * всё ещё поднята -- PIC доставит то же самое прерывание СРАЗУ ЖЕ
 * повторно, буквально на первой же границе, где IF снова станет 1
 * (то есть прямо на iretq, которым мы пытаемся вернуться в ring 3,
 * ДО того, как разбуженная задача успеет выполнить хоть одну
 * инструкцию) -- бесконечный шторм прерываний на одном и том же rip,
 * который на верхнем уровне неотличим от "процесс никогда не
 * возобновляется": именно это и происходило. Маскируем линию здесь же
 * (до sem_post) -- задача проснётся и займётся кадром спокойно, а
 * irqbridge_wait() снова размаскирует линию перед СЛЕДУЮЩИМ ожиданием,
 * когда устройство уже точно подтверждено. */
static void irq_bridge_dispatch(registers_t *regs) {
    u64 vec = regs->int_no;
    if (vec < 32 || vec >= 48) return; /* не должно случиться -- нас регистрируют только на IRQ-векторы */
    u8 irq = (u8)(vec - 32);
    pic_set_mask(irq);
    sem_post(&g_irq_sem[irq]);
}

bool_t irqbridge_wait(u8 irq) {
    if (irq >= 16) return FALSE;

    if (!g_bridge_owns[irq]) {
        /* Ещё не наша линия -- проверяем, что её вообще никто не занял
           (драйвер ядра) ДО того, как мы попробуем её перехватить.
           Гонка "два процесса одновременно первый раз ждут одну и ту
           же ещё не застолбленную линию" на однопроцессорной системе
           невозможна (между проверкой и установкой нет yield), а на
           SMP -- см. известное ограничение в CONTAINER_ARCHITECTURE.md
           (Фаза 4, подшаг 2): здесь сознательно не введён отдельный
           спинлок ради этого редкого случая. */
        if (irq_handler_is_registered(irq)) {
            return FALSE; /* уже владеет драйвер ядра (таймер, сетевая карта...) */
        }
        irq_register_handler(irq, irq_bridge_dispatch);
        g_bridge_owns[irq] = TRUE;
    }

    /* См. общий комментарий у irq_bridge_dispatch() выше: линия могла
       остаться замаскированной с прошлого срабатывания (или ещё не
       размаскирована вовсе, если это первый вызов) -- размаскируем
       заново перед КАЖДЫМ ожиданием, а не только один раз при первом
       захвате линии. */
    pic_clear_mask(irq);
    sem_wait(&g_irq_sem[irq]);
    return TRUE;
}
